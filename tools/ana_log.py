def phase2_as_float(value: Any) -> float:
    number = to_float(value)
    return number if number is not None else math.nan


def phase2_finite(value: Any) -> bool:
    return to_float(value) is not None


def phase2_fmt(value: Any) -> str:
    number = to_float(value)
    return f"{number:.9f}" if number is not None else "nan"


def phase2_usable_plot_value(value: Any, sentinel_abs: float = PHASE2_SENTINEL_ABS) -> float | None:
    number = to_float(value)
    if number is None or abs(number) >= sentinel_abs:
        return None
