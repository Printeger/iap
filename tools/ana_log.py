PACKAGE_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RUN = PACKAGE_ROOT / "log" / "latest"

RUNTIME_LOG_RE = re.compile(
    r"^\[(?P<ts>[^\]]+)\]\s+\[(?P<logger>[^\]]+)\]\s+\[(?P<level>[^\]]+)\]\s+(?P<message>.*)$"
)
NUMBER_RE = re.compile(r"\b\d+(?:\.\d+)?\b")


@dataclass
class ArtifactStatus:
    name: str
    rel_path: str
    status: str
    reason: str
    rows: int | None = None
    size_bytes: int = 0
    note: str = ""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Analyze one current-format IAP run directory.")
    parser.add_argument("--run", default=str(DEFAULT_RUN), help=f"Run directory to analyze (default: {DEFAULT_RUN})")
    parser.add_argument("--out", default="", help="Output analysis directory (default: <run>/analysis)")
    parser.add_argument("--no-plots", action="store_true", help="Skip plots generated by ana_log.py")
    parser.add_argument("--skip-external-tools", action="store_true", help="Do not invoke ICP/GNSS/ARAIM plot scripts")
    parser.add_argument("--strict", action="store_true", help="Exit non-zero if runtime errors or enabled current artifacts are missing")
    return parser.parse_args()


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def resolve_run_dir(run_arg: str) -> Path:
    candidate = Path(run_arg)
    if not candidate.is_absolute() and not candidate.exists():
        candidate = PACKAGE_ROOT / run_arg
    candidate = candidate.resolve()
    if not candidate.exists():
        raise FileNotFoundError(f"Run path does not exist: {candidate}")
    if not candidate.is_dir():
        raise NotADirectoryError(f"Run path is not a directory: {candidate}")
    return candidate


def strip_json_comments(text: str) -> str:
    result: list[str] = []
    i = 0
    in_string = False
    quote = ""
    while i < len(text):
        ch = text[i]
        nxt = text[i + 1] if i + 1 < len(text) else ""
        if in_string:
            result.append(ch)
            if ch == "\\" and i + 1 < len(text):
                result.append(text[i + 1])
                i += 2
                continue
            if ch == quote:
                in_string = False
            i += 1
            continue
        if ch in {"'", '"'}:
            in_string = True
            quote = ch
            result.append(ch)
            i += 1
            continue
        if ch == "/" and nxt == "/":
            i += 2
            while i < len(text) and text[i] != "\n":
                i += 1
            continue
        if ch == "/" and nxt == "*":
            i += 2
            while i + 1 < len(text) and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2
            continue
        result.append(ch)
        i += 1
    return "".join(result)


def load_jsonish(path: Path) -> Any:
    if not path.exists() or path.stat().st_size == 0:
        return None
    text = path.read_text(encoding="utf-8", errors="replace")
    if not text.strip():
        return None
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return json.loads(strip_json_comments(text))


def load_csv_rows(path: Path) -> list[dict[str, str]]:
    if not path.exists() or path.stat().st_size == 0:
        return []
    with path.open("r", encoding="utf-8", errors="replace", newline="") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames:
            return []
        return [dict(row) for row in reader]


def to_float(value: Any) -> float | None:
    if value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    text = str(value).strip()
    if text == "":
        return None
    try:
        number = float(text)
    except ValueError:
        return None
    if not math.isfinite(number):
        return None
    return number


def numeric_values(rows: list[dict[str, str]], column: str) -> list[float]:
    values = []
    for row in rows:
        value = to_float(row.get(column))
        if value is not None:
            values.append(value)
    return values


def first_value(row: dict[str, str], columns: list[str]) -> Any:
    for column in columns:
        value = row.get(column)
        if value not in (None, ""):
            return value
    return None


def first_number(row: dict[str, str], columns: list[str]) -> float | None:
    return to_float(first_value(row, columns))


def numeric_values_any(rows: list[dict[str, str]], columns: list[str]) -> list[float]:
    values = []
    for row in rows:
        value = first_number(row, columns)
        if value is not None:
            values.append(value)
    return values


def boolish(value: Any) -> bool | None:
    if value is None:
        return None
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return value != 0
    text = str(value).strip().lower()
    if text in {"1", "true", "yes", "on", "y"}:
        return True
    if text in {"0", "false", "no", "off", "n"}:
        return False
    return None


def quantile(values: list[float], q: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    if len(ordered) == 1:
        return float(ordered[0])
    pos = (len(ordered) - 1) * q
    lower = math.floor(pos)
    upper = math.ceil(pos)
    if lower == upper:
        return float(ordered[lower])
    weight = pos - lower
    return float(ordered[lower] * (1.0 - weight) + ordered[upper] * weight)


def stats(values: list[float]) -> dict[str, float | int]:
    if not values:
        return {"count": 0, "mean": 0.0, "p50": 0.0, "p95": 0.0, "p99": 0.0, "max": 0.0, "min": 0.0}
    return {
        "count": len(values),
        "mean": float(mean(values)),
        "p50": float(median(values)),
        "p95": quantile(values, 0.95),
        "p99": quantile(values, 0.99),
        "max": float(max(values)),
        "min": float(min(values)),
    }


def rms(values: list[float]) -> float:
    if not values:
        return 0.0
    return math.sqrt(sum(v * v for v in values) / len(values))


def human_size(size_bytes: int) -> str:
    value = float(size_bytes)
    for suffix in ["B", "KiB", "MiB", "GiB"]:
        if value < 1024.0 or suffix == "GiB":
            return f"{value:.1f} {suffix}" if suffix != "B" else f"{int(value)} B"
        value /= 1024.0
    return f"{size_bytes} B"


def normalize_message(message: str) -> str:
    msg = NUMBER_RE.sub("<n>", message)
    msg = re.sub(r"/[A-Za-z0-9_./-]+", "<path>", msg)
    return msg[:200]


def md_table(headers: list[str], rows: list[list[Any]]) -> str:
    def fmt(value: Any) -> str:
        text = str(value)
        return text.replace("\n", "<br>").replace("|", "\\|")

    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(fmt(item) for item in row) + " |")
    return "\n".join(lines)


def first_existing(run_dir: Path, candidates: list[str]) -> tuple[Path, str] | tuple[None, str]:
    for rel_path in candidates:
        path = run_dir / rel_path
        if path.exists():
            return path, rel_path
    return None, candidates[0]


def artifact_paths(run_dir: Path) -> dict[str, tuple[Path | None, str, list[str]]]:
    aliases = {
        "run_info": ["metadata/run_info.json"],
        "timing": ["profiling/iap_timing.csv", "profiling/pipeline_timing.csv"],
        "icp": ["export/iap_icp.csv", "export/icp_quality.csv"],
        "gnss_factor_debug": ["export/iap_gnss_factor_debug.csv", "export/gnss_factor_debug.csv"],
        "araim": ["export/iap_araim.csv", "export/araim.csv"],
        "trajectory": ["export/traj_with_gnss.csv", "export/integrity_trajectory.csv"],
        "truth_vs_est": ["export/iap_sim_truth_vs_est.csv", "export/sim_truth_vs_est.csv"],
        "desired_vs_truth": ["export/desired_vs_truth.csv", "export/tracking_error.csv"],
    }
    result = {}
    for name, candidates in aliases.items():
        path, rel = first_existing(run_dir, candidates)
        result[name] = (path, rel, candidates)
    return result


def config_enabled(configs: dict[str, Any], artifact_name: str) -> bool | None:
    config_json = configs.get("config")
    config_gnss = configs.get("config_gnss")
    config_odom = (
        configs.get("config_odometry")
        or configs.get("config_odometry_gpu")
        or configs.get("config_odometry_cpu")
    )
    config_ros = configs.get("config_ros")

    if artifact_name == "timing":
        return nested_bool(config_json, ["global", "enable_timing_csv"])
    if artifact_name == "icp":
        return nested_bool(config_odom, ["odometry_estimation", "enable_icp_csv"])
    if artifact_name == "gnss_factor_debug":
        return nested_bool(config_gnss, ["gnss", "enable_debug_csv"])
    if artifact_name == "araim":
        return nested_bool(config_gnss, ["integrity", "enable_araim_csv"])
    if artifact_name == "trajectory":
        return nested_bool(config_gnss, ["integrity", "enable_traj_csv"])
    if artifact_name == "truth_vs_est":
        return nested_bool(config_ros, ["glim_ros", "sim", "enable_metrics_csv"])
    if artifact_name == "dump":
        local_mapping = nested_bool(config_ros, ["glim_ros", "enable_local_mapping"])
        global_mapping = nested_bool(config_ros, ["glim_ros", "enable_global_mapping"])
        if local_mapping is None and global_mapping is None:
            return None
        return bool(local_mapping or global_mapping)
    return None


def nested_get(obj: Any, path: list[str]) -> Any:
    cur = obj
    for key in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(key)
    return cur


def nested_bool(obj: Any, path: list[str]) -> bool | None:
    value = nested_get(obj, path)
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return bool(value)
    if isinstance(value, str):
        low = value.strip().lower()
        if low in {"1", "true", "yes", "on"}:
            return True
        if low in {"0", "false", "no", "off"}:
            return False
    return None


def load_metadata(run_dir: Path) -> dict[str, Any]:
    metadata_dir = run_dir / "metadata"
    config_dir = metadata_dir / "config"
    run_info = load_jsonish(metadata_dir / "run_info.json") or {}
    configs: dict[str, Any] = {}
    if config_dir.exists():
        for config_file in sorted(config_dir.glob("*.json")):
            configs[config_file.stem] = load_jsonish(config_file)

    legacy: dict[str, Any] = {}
    for name in ["config_snapshot.json", "git_rev.txt", "build_info.txt"]:
        path = metadata_dir / name
        if path.exists():
            legacy[name] = path.read_text(encoding="utf-8", errors="replace").strip()

    return {"run_info": run_info, "configs": configs, "legacy": legacy}


def parse_runtime_logs(run_dir: Path) -> dict[str, Any]:
    runtime_dir = run_dir / "runtime"
    summary: dict[str, Any] = {
        "files": [],
        "total_lines": 0,
        "level_counts": Counter(),
        "logger_counts": Counter(),
        "issues": [],
        "pattern_counts": Counter(),
        "loaded_modules": [],
        "shutdown_messages": [],
        "save_messages": [],
    }
    if not runtime_dir.exists():
        return summary

    for log_path in sorted(runtime_dir.glob("*.log")):
        file_summary = {"file": log_path.name, "lines": 0, "level_counts": Counter()}
        for line_no, raw in enumerate(log_path.read_text(encoding="utf-8", errors="replace").splitlines(), start=1):
            file_summary["lines"] += 1
            summary["total_lines"] += 1
            match = RUNTIME_LOG_RE.match(raw)
            if not match:
                continue
            level = match.group("level").lower()
            logger = match.group("logger")
            message = match.group("message")
            file_summary["level_counts"][level] += 1
            summary["level_counts"][level] += 1
            summary["logger_counts"][logger] += 1
            if "load lib" in message:
                summary["loaded_modules"].append(message.replace("load ", "", 1))
            if "waiting for" in message or "shutdown" in message.lower():
                summary["shutdown_messages"].append(message)
            if "saving" in message or "serializing" in message or "dump" in message:
                summary["save_messages"].append(message)
            if level in {"warn", "warning", "error", "critical"}:
                issue = {"file": log_path.name, "line": line_no, "level": level, "message": message}
                summary["issues"].append(issue)
                summary["pattern_counts"][normalize_message(message)] += 1
        summary["files"].append(file_summary)

    summary["top_patterns"] = summary["pattern_counts"].most_common(10)
    return summary


def scan_artifacts(run_dir: Path, metadata: dict[str, Any]) -> list[ArtifactStatus]:
    configs = metadata.get("configs", {})
    paths = artifact_paths(run_dir)
    artifacts: list[ArtifactStatus] = []

    for name, (path, rel_path, candidates) in paths.items():
        exists = path is not None and path.exists()
        size = path.stat().st_size if exists and path is not None else 0
        rows: int | None = None
        if exists and path is not None and path.suffix == ".csv":
            rows = len(load_csv_rows(path))

        enabled = config_enabled(configs, name)
        if exists and size > 0 and (rows is None or rows > 0):
            status = "found"
            reason = "found_with_data"
        elif exists:
            status = "empty"
            reason = "empty_file"
        elif enabled is False:
            status = "disabled"
            reason = "expected_missing_by_config"
        elif enabled is True:
            status = "expected_missing"
            reason = "enabled_but_missing"
        else:
            status = "missing"
            reason = "availability_unclear"

        note = ""
        if len(candidates) > 1:
            note = "aliases: " + ", ".join(candidates)
        artifacts.append(ArtifactStatus(name, rel_path, status, reason, rows, size, note))

    config_files = sorted((run_dir / "metadata" / "config").glob("*.json"))
    artifacts.append(
        ArtifactStatus(
            "config_snapshot",
            "metadata/config/*.json",
            "found" if config_files else "missing",
            "found_with_data" if config_files else "missing_config_snapshot",
            rows=len(config_files),
            size_bytes=sum(path.stat().st_size for path in config_files),
            note=f"{len(config_files)} config files",
        )
    )

    runtime_files = sorted((run_dir / "runtime").glob("*.log"))
    artifacts.append(
        ArtifactStatus(
            "runtime_logs",
            "runtime/*.log",
            "found" if runtime_files else "missing",
            "found_with_data" if runtime_files else "missing_runtime_logs",
            rows=len(runtime_files),
            size_bytes=sum(path.stat().st_size for path in runtime_files),
            note=f"{len(runtime_files)} log files",
        )
    )

    dump_dir = run_dir / "export" / "dump"
    dump_files = [path for path in dump_dir.rglob("*") if path.is_file()] if dump_dir.exists() else []
    dump_enabled = config_enabled(configs, "dump")
    if dump_files:
        status, reason = "found", "found_with_data"
    elif dump_enabled is False:
        status, reason = "disabled", "expected_missing_by_config"
    elif dump_enabled is True:
        status, reason = "expected_missing", "enabled_but_missing"
    else:
        status, reason = "missing", "availability_unclear"
    artifacts.append(
        ArtifactStatus(
            "dump_export",
            "export/dump/*",
            status,
            reason,
            rows=len(dump_files),
            size_bytes=sum(path.stat().st_size for path in dump_files),
            note=f"{len(dump_files)} files",
        )
    )
    return artifacts


def analyze_timing(rows: list[dict[str, str]]) -> dict[str, Any]:
    if not rows:
        return {"available": False}
    by_module: dict[str, list[float]] = defaultdict(list)
    for row in rows:
        module = row.get("module", "").strip() or "unknown"
        elapsed = first_number(row, ["elapsed_ms", "duration_ms", "time_ms", "ms", "elapsed", "duration"])
        if elapsed is not None:
            by_module[module].append(elapsed)
    module_stats = []
    for module, values in by_module.items():
        item = {"module": module, **stats(values)}
        module_stats.append(item)
    module_stats.sort(key=lambda item: float(item["mean"]), reverse=True)
    return {"available": True, "row_count": len(rows), "module_stats": module_stats}


def analyze_icp(rows: list[dict[str, str]]) -> dict[str, Any]:
    if not rows:
        return {"available": False}
    drop_flags = []
    for row in rows:
        drop_value = first_value(row, ["drop_flag", "is_degenerate", "degenerate"])
        drop_flags.append(boolish(drop_value) is True)
    return {
        "available": True,
        "frame_count": len(rows),
        "degenerate_count": sum(1 for value in drop_flags if value),
        "degenerate_ratio": sum(1 for value in drop_flags if value) / max(len(rows), 1),
        "rmse": stats(numeric_values(rows, "rmse")),
        "inlier_fraction": stats(numeric_values(rows, "inlier_fraction")),
        "condition_number": stats(numeric_values(rows, "condition_number")),
        "gamma_lidar": stats(numeric_values(rows, "gamma_lidar")),
    }


def analyze_gnss(rows: list[dict[str, str]]) -> dict[str, Any]:
    if not rows:
        return {"available": False}
    factor_counts = Counter((first_value(row, ["factor_type", "type"]) or "unknown").strip() for row in rows)
    sat_labels = {
        f"{row.get('constellation', '').strip()}{str(first_value(row, ['sat_id', 'sat']) or '').strip()}"
        for row in rows
        if first_value(row, ["sat_id", "sat"])
    }
    constellations = {row.get("constellation", "").strip() for row in rows if row.get("constellation")}
    residual_by_type: dict[str, list[float]] = defaultdict(list)
    norm_by_type: dict[str, list[float]] = defaultdict(list)
    for row in rows:
        ftype = (first_value(row, ["factor_type", "type"]) or "unknown").strip()
        residual = to_float(row.get("residual"))
        normalized = to_float(row.get("normalized_residual"))
        if residual is not None:
            residual_by_type[ftype].append(residual)
        if normalized is not None:
            norm_by_type[ftype].append(normalized)

    type_stats = {}
    for ftype in sorted(set(residual_by_type) | set(norm_by_type)):
        type_stats[ftype] = {
            "residual_rms": rms(residual_by_type.get(ftype, [])),
            "normalized_residual_rms": rms(norm_by_type.get(ftype, [])),
            "residual": stats(residual_by_type.get(ftype, [])),
            "normalized_residual": stats(norm_by_type.get(ftype, [])),
        }

    return {
        "available": True,
        "row_count": len(rows),
        "factor_counts": dict(factor_counts),
        "satellite_count": len(sat_labels),
        "constellation_count": len(constellations),
        "constellations": sorted(constellations),
        "type_stats": type_stats,
    }


def analyze_araim(rows: list[dict[str, str]]) -> dict[str, Any]:
    if not rows:
        return {"available": False}
    epochs = [row for row in rows if row.get("row_type") == "epoch"]
    worst_hyp = [row for row in rows if row.get("row_type") == "worst_hyp"]
    states = Counter(row.get("state", "unknown") for row in epochs)
    unsafe_count = states.get("UNSAFE", 0)
    return {
        "available": True,
        "row_count": len(rows),
        "epoch_count": len(epochs),
        "worst_hyp_count": len(worst_hyp),
        "state_counts": dict(states),
        "unsafe_ratio": unsafe_count / max(len(epochs), 1),
        "HPL": stats(numeric_values(epochs, "HPL")),
        "VPL": stats(numeric_values(epochs, "VPL")),
        "HAL": stats(numeric_values(epochs, "HAL")),
        "VAL": stats(numeric_values(epochs, "VAL")),
        "IM": stats(numeric_values(epochs, "IM")),
        "n_hyp": stats(numeric_values(epochs, "n_hyp")),
        "n_det": stats(numeric_values(epochs, "n_det")),
    }


def analyze_trajectory(rows: list[dict[str, str]]) -> dict[str, Any]:
    if not rows:
        return {"available": False}
    stamps = numeric_values_any(rows, ["stamp", "timestamp", "time"])
    xs = numeric_values(rows, "x")
    ys = numeric_values(rows, "y")
    zs = numeric_values(rows, "z")
    span_s = max(stamps) - min(stamps) if len(stamps) >= 2 else 0.0
    path_length = 0.0
    points = []
    for row in rows:
        x, y, z = to_float(row.get("x")), to_float(row.get("y")), to_float(row.get("z"))
        if x is not None and y is not None and z is not None:
            points.append((x, y, z))
    for prev, cur in zip(points, points[1:]):
        path_length += math.sqrt(sum((cur[i] - prev[i]) ** 2 for i in range(3)))
    return {
        "available": True,
        "row_count": len(rows),
        "span_s": span_s,
        "path_length_m": path_length,
        "x": stats(xs),
        "y": stats(ys),
        "z": stats(zs),
    }


def config_time_tolerance_s(metadata: dict[str, Any]) -> float:
    configs = metadata.get("configs", {})
    value = nested_get(configs.get("config_gnss"), ["gnss", "time_tolerance"])
    number = to_float(value)
    if number is None or number <= 0.0:
        return 0.1
    return number


def truth_est_row_to_sample(row: dict[str, str]) -> dict[str, float] | None:
    values = {
        "truth_stamp": to_float(row.get("truth_stamp")),
        "est_stamp": to_float(row.get("est_stamp")),
        "truth_x": to_float(row.get("truth_x")),
        "truth_y": to_float(row.get("truth_y")),
        "truth_z": to_float(row.get("truth_z")),
        "est_x": to_float(row.get("est_x")),
        "est_y": to_float(row.get("est_y")),
        "est_z": to_float(row.get("est_z")),
    }
    if any(value is None for value in values.values()):
        return None
    return {key: float(value) for key, value in values.items() if value is not None}


def nearest_sample_by_stamp(
    samples: list[dict[str, float]],
    stamps: list[float],
    target_stamp: float,
) -> tuple[dict[str, float] | None, float]:
    if not samples:
        return None, math.inf
    index = bisect.bisect_left(stamps, target_stamp)
    candidates = []
    if index < len(samples):
        candidates.append(samples[index])
    if index > 0:
        candidates.append(samples[index - 1])
    best = min(candidates, key=lambda item: abs(item["est_stamp"] - target_stamp))
    return best, abs(best["est_stamp"] - target_stamp)


def analyze_sim_truth_integrity(
    truth_rows: list[dict[str, str]],
    araim_rows: list[dict[str, str]],
    metadata: dict[str, Any],
) -> dict[str, Any]:
    if not truth_rows:
        return {"available": False, "reason": "missing export/iap_sim_truth_vs_est.csv"}
    if not araim_rows:
        return {"available": False, "reason": "missing export/iap_araim.csv"}

    samples = [sample for row in truth_rows if (sample := truth_est_row_to_sample(row)) is not None]
    samples.sort(key=lambda item: item["est_stamp"])
    stamps = [item["est_stamp"] for item in samples]
    epochs = [row for row in araim_rows if row.get("row_type") == "epoch"]
    match_tolerance_s = config_time_tolerance_s(metadata)
    validation_rows: list[dict[str, Any]] = []
    unmatched = 0
    match_method = "nearest_est_stamp"

    def append_validation_row(epoch: dict[str, str], sample: dict[str, float], stamp: float, match_dt: float | None) -> None:
        if stamp is None:
            return
        err_e = sample["est_x"] - sample["truth_x"]
        err_n = sample["est_y"] - sample["truth_y"]
        err_u = sample["est_z"] - sample["truth_z"]
        horizontal_error = math.hypot(err_e, err_n)
        vertical_error = abs(err_u)
        position_error = math.sqrt(err_e * err_e + err_n * err_n + err_u * err_u)
        hpl = to_float(epoch.get("HPL")) or 0.0
        vpl = to_float(epoch.get("VPL")) or 0.0
        hal = to_float(epoch.get("HAL")) or 0.0
        val = to_float(epoch.get("VAL")) or 0.0
        state = (epoch.get("state") or "unknown").strip()
        hpl_covers = horizontal_error <= hpl
        vpl_covers = vertical_error <= vpl
        safe_but_hazard = state == "SAFE" and (horizontal_error > hal or vertical_error > val)
        unsafe_but_within_alert = state == "UNSAFE" and horizontal_error <= hal and vertical_error <= val

        validation_rows.append({
            "stamp": stamp,
            "match_dt_s": match_dt,
            "truth_stamp": sample["truth_stamp"],
            "est_stamp": sample["est_stamp"],
            "truth_x": sample["truth_x"],
            "truth_y": sample["truth_y"],
            "truth_z": sample["truth_z"],
            "est_x": sample["est_x"],
            "est_y": sample["est_y"],
            "est_z": sample["est_z"],
            "err_e": err_e,
            "err_n": err_n,
            "err_u": err_u,
            "horizontal_error_m": horizontal_error,
            "vertical_error_m": vertical_error,
            "position_error_m": position_error,
            "HPL": hpl,
            "VPL": vpl,
            "HAL": hal,
            "VAL": val,
            "IM": to_float(epoch.get("IM")) or 0.0,
            "state": state,
            "hpl_covers_error": hpl_covers,
            "vpl_covers_error": vpl_covers,
            "safe_but_hazard": safe_but_hazard,
            "unsafe_but_within_alert": unsafe_but_within_alert,
            "n_sv": to_float(epoch.get("n_sv")) or 0.0,
            "n_const": to_float(epoch.get("n_const")) or 0.0,
            "PDOP": to_float(epoch.get("PDOP")) or 0.0,
            "n_hyp": to_float(epoch.get("n_hyp")) or 0.0,
            "n_det": to_float(epoch.get("n_det")) or 0.0,
        })

    for epoch in epochs:
        stamp = to_float(epoch.get("stamp"))
        if stamp is None:
            unmatched += 1
            continue
        sample, match_dt = nearest_sample_by_stamp(samples, stamps, stamp)
        if sample is None or match_dt > match_tolerance_s:
            unmatched += 1
            continue
        append_validation_row(epoch, sample, stamp, match_dt)

    if not validation_rows and samples and epochs:
        epoch_stamps = [to_float(row.get("stamp")) for row in epochs]
        epoch_stamps = [stamp for stamp in epoch_stamps if stamp is not None]
        if len(epoch_stamps) >= 2:
            match_method = "relative_index_fallback_low_precision_stamp"
            validation_rows.clear()
            unmatched = 0
            epoch_t0 = min(epoch_stamps)
            epoch_t1 = max(epoch_stamps)
            for epoch in epochs:
                stamp = to_float(epoch.get("stamp"))
                if stamp is None:
                    unmatched += 1
                    continue
                alpha = (stamp - epoch_t0) / (epoch_t1 - epoch_t0) if not math.isclose(epoch_t0, epoch_t1) else 0.0
                alpha = min(max(alpha, 0.0), 1.0)
                index = min(max(int(round(alpha * (len(samples) - 1))), 0), len(samples) - 1)
                append_validation_row(epoch, samples[index], stamp, None)

    matched = len(validation_rows)
    state_counts = Counter(str(row["state"]) for row in validation_rows)
    hpl_ok = sum(1 for row in validation_rows if row["hpl_covers_error"])
    vpl_ok = sum(1 for row in validation_rows if row["vpl_covers_error"])
    both_ok = sum(1 for row in validation_rows if row["hpl_covers_error"] and row["vpl_covers_error"])
    false_safe = sum(1 for row in validation_rows if row["safe_but_hazard"])
    conservative_unsafe = sum(1 for row in validation_rows if row["unsafe_but_within_alert"])
    he = [float(row["horizontal_error_m"]) for row in validation_rows]
    ve = [float(row["vertical_error_m"]) for row in validation_rows]
    pe = [float(row["position_error_m"]) for row in validation_rows]
    h_margin = [float(row["HPL"]) - float(row["horizontal_error_m"]) for row in validation_rows]
    v_margin = [float(row["VPL"]) - float(row["vertical_error_m"]) for row in validation_rows]

    return {
        "available": matched > 0,
        "reason": "" if matched > 0 else "no ARAIM epoch matched truth estimate rows within tolerance",
        "match_tolerance_s": match_tolerance_s,
        "match_method": match_method,
        "truth_row_count": len(truth_rows),
        "valid_truth_row_count": len(samples),
        "araim_epoch_count": len(epochs),
        "matched_epoch_count": matched,
        "unmatched_epoch_count": unmatched + max(len(epochs) - matched - unmatched, 0),
        "state_counts": dict(state_counts),
        "hpl_coverage_ratio": hpl_ok / max(matched, 1),
        "vpl_coverage_ratio": vpl_ok / max(matched, 1),
        "hv_coverage_ratio": both_ok / max(matched, 1),
        "false_safe_count": false_safe,
        "false_safe_ratio": false_safe / max(matched, 1),
        "conservative_unsafe_count": conservative_unsafe,
        "conservative_unsafe_ratio": conservative_unsafe / max(matched, 1),
        "horizontal_error": stats(he),
        "vertical_error": stats(ve),
        "position_error": stats(pe),
        "horizontal_error_rms": rms(he),
        "vertical_error_rms": rms(ve),
        "position_error_rms": rms(pe),
        "horizontal_pl_margin": stats(h_margin),
        "vertical_pl_margin": stats(v_margin),
        "rows": validation_rows,
    }


