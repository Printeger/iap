def run_external_plot(script: Path, args: list[str]) -> dict[str, Any]:
    proc = subprocess.run([sys.executable, str(script), *args], capture_output=True, text=True, check=False)
    return {
        "script": script.name,
        "returncode": proc.returncode,
        "stdout": proc.stdout.strip(),
        "stderr": proc.stderr.strip(),
    }


def integrate_external_plots(run_dir: Path, rows_by_name: dict[str, list[dict[str, str]]], out_dir: Path) -> list[dict[str, Any]]:
    results: list[dict[str, Any]] = []
    ensure_dir(out_dir)
    paths = artifact_paths(run_dir)
    icp_path = paths["icp"][0]
    timing_path = paths["timing"][0]
    if icp_path and timing_path and rows_by_name.get("icp") and rows_by_name.get("timing"):
        icp_out = out_dir / "icp"
        ensure_dir(icp_out)
        results.append(run_external_plot(PACKAGE_ROOT / "tools" / "plot_icp_timing.py", [str(icp_path), str(timing_path), str(icp_out)]))
    gnss_path = paths["gnss_factor_debug"][0]
    if gnss_path and rows_by_name.get("gnss_factor_debug"):
        gnss_out = out_dir / "gnss_factor_debug"
        ensure_dir(gnss_out)
        results.append(run_external_plot(PACKAGE_ROOT / "tools" / "plot_gnss_factor_debug.py", ["--csv", str(gnss_path), "--out", str(gnss_out)]))
    araim_path = paths["araim"][0]
    if araim_path and rows_by_name.get("araim"):
        araim_out = out_dir / "araim"
        ensure_dir(araim_out)
        results.append(run_external_plot(PACKAGE_ROOT / "tools" / "plot_araim_timeline.py", [str(araim_path), str(araim_out)]))
    return results


