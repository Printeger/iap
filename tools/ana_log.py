ARAIM_PLOT_SENTINEL_ABS = 1.0e8


def araim_plot_value(row: dict[str, str], key: str) -> float | None:
    value = to_float(row.get(key))
    if value is None or abs(value) >= ARAIM_PLOT_SENTINEL_ABS:
        return None
    return value


def araim_epoch_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    return [
        row
        for row in rows
        if row.get("row_type") == "epoch" and to_float(row.get("stamp")) is not None
    ]


def araim_points(
    rows: list[dict[str, str]],
    value_key: str,
    plot_x: float,
    plot_y: float,
    plot_w: float,
    plot_h: float,
    t0: float,
    t1: float,
    y0: float,
    y1: float,
) -> list[tuple[float, float]]:
    points = []
    for row in rows:
        stamp = to_float(row.get("stamp"))
        value = araim_plot_value(row, value_key)
        if stamp is None or value is None:
            continue
        x = map_linear(stamp, t0, t1, plot_x, plot_x + plot_w)
        y = map_linear(value, y0, y1, plot_y + plot_h, plot_y)
        points.append((x, y))
    return points


def araim_values(rows: list[dict[str, str]], key: str) -> list[float]:
    values = []
    for row in rows:
        value = araim_plot_value(row, key)
        if value is not None:
            values.append(value)
    return values


