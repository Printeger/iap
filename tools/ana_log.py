def phase2_hex_to_rgb(color: str) -> tuple[int, int, int]:
    value = color.lstrip("#")
    if len(value) != 6:
        return 0, 0, 0
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def phase2_rgb_to_hex(rgb: tuple[int, int, int]) -> str:
    return "#" + "".join(f"{max(0, min(255, channel)):02x}" for channel in rgb)


def phase2_lerp_color(lo_color: str, hi_color: str, alpha: float) -> str:
    alpha = min(max(alpha, 0.0), 1.0)
    lo = phase2_hex_to_rgb(lo_color)
    hi = phase2_hex_to_rgb(hi_color)
    return phase2_rgb_to_hex(
        tuple(int(round(lo[idx] * (1.0 - alpha) + hi[idx] * alpha)) for idx in range(3))
    )


def phase2_value_color(value: float, lo: float, hi: float, palette: tuple[str, str, str] = ("#2563eb", "#16a34a", "#dc2626")) -> str:
    if not math.isfinite(value):
        return "#94a3b8"
    if math.isclose(lo, hi):
        return palette[1]
    mid = (lo + hi) * 0.5
    if value <= mid:
        alpha = (value - lo) / max(mid - lo, 1e-12)
        return phase2_lerp_color(palette[0], palette[1], alpha)
    alpha = (value - mid) / max(hi - mid, 1e-12)
    return phase2_lerp_color(palette[1], palette[2], alpha)


def svg_line(x1: float, y1: float, x2: float, y2: float, color: str, width: float = 1.2, opacity: float = 1.0, dash: str = "") -> str:
    dash_attr = f' stroke-dasharray="{dash}"' if dash else ""
    return (
        f'<line x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" '
        f'stroke="{color}" stroke-width="{width:.2f}" stroke-opacity="{opacity:.3f}"{dash_attr} />'
    )


def svg_circle(cx: float, cy: float, r: float, color: str, opacity: float = 1.0, stroke: str = "none", stroke_width: float = 0.0) -> str:
    stroke_attr = f' stroke="{stroke}" stroke-width="{stroke_width:.2f}"' if stroke != "none" else ""
    return (
        f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r:.2f}" fill="{color}" fill-opacity="{opacity:.3f}"{stroke_attr} />'
    )


def generate_phase2_prediction_timeline_svg(analysis: dict[str, Any], path: Path) -> None:
    width, height = 1120, 900
    body: list[str] = [svg_text(40, 34, "Phase 2 Planner Integrity Prediction Timeline", 18, "#111827")]
    online_rows = phase2_sorted_by_time(analysis.get("online_rows", []), "sample_abs_time")
    aligned_rows = phase2_sorted_by_time(analysis.get("rows", []), "sample_abs_time")
    if not online_rows:
        body.append(svg_text(40, 80, "No Phase 2 prediction rows were available.", 14, "#991b1b"))
        write_svg(path, width, height, body)
        return

    t0, t1 = phase2_time_bounds(online_rows, "sample_abs_time")
    rel_label = f"relative time from {t0:.3f}s"

    def add_risk_ticks(px: float, py: float, pw: float, ph: float) -> None:
        stride = max(1, len(online_rows) // 700)
        for row in online_rows[::stride]:
            stamp = to_float(row.get("sample_abs_time"))
            if stamp is None:
                continue
            x = map_linear(stamp, t0, t1, px, px + pw)
            body.append(
                f'<line x1="{x:.2f}" y1="{py + ph - 14:.2f}" x2="{x:.2f}" y2="{py + ph:.2f}" '
                f'stroke="{phase2_risk_color(row.get("risk_state_pred"))}" stroke-opacity="0.55" />'
            )

    def add_panel(
        px: float,
        py: float,
        pw: float,
        ph: float,
        title: str,
        ylabel: str,
        series: list[tuple[list[dict[str, Any]], str, str, str, bool]],
        zero_floor: bool = False,
    ) -> None:
        values: list[float] = []
        for rows, key, _label, _color, skip_sentinel in series:
            values.extend(phase2_series_values(rows, [key], skip_sentinel))
        y0, y1 = float_range(values)
        if zero_floor:
            y0 = min(0.0, y0)
        body.extend(svg_axes(px, py, pw, ph, title, rel_label, ylabel))
        drew = False
        for rows, key, label, color, skip_sentinel in series:
            points = phase2_time_points(rows, "sample_abs_time", key, px, py, pw, ph, t0, t1, y0, y1, skip_sentinel)
            if points:
                body.append(svg_polyline(points, color, 1.8, 0.92))
                drew = True
        if not drew:
            body.append(svg_text(px + 20, py + 42, "No usable finite values in the zoomed range.", 13, "#991b1b"))
        add_risk_ticks(px, py, pw, ph)
        body.extend(svg_legend_group(px + pw - 190, py + 18, [
            (label, color) for _rows, _key, label, color, _skip_sentinel in series
        ]))
        body.append(svg_text(px - 10, py + ph + 4, f"{y0:.2f}", 10, "#4b5563", "end"))
        body.append(svg_text(px - 10, py + 4, f"{y1:.2f}", 10, "#4b5563", "end"))

    add_panel(
        70.0,
        80.0,
        990.0,
        210.0,
        "Predicted integrity margin",
        "IM [m]",
        [(online_rows, "IM_pred", "IM_pred (<1e8 abs)", "#dc2626", True)],
    )
    if not phase2_series_values(online_rows, ["IM_pred"], True):
        body.append(svg_text(90, 132, "All IM_pred values are sentinel-scale; risk ticks still show SAFE/MARGINAL/UNSAFE samples.", 12, "#4b5563"))

    add_panel(
        70.0,
        360.0,
        990.0,
        210.0,
        "Predicted alert/protection limits and clearances",
        "meters",
        [
            (online_rows, "AL_pred", "AL_pred", "#16a34a", True),
            (online_rows, "AL_H_pred", "AL_H_pred", "#0891b2", True),
            (online_rows, "AL_V_pred", "AL_V_pred", "#f97316", True),
            (online_rows, "PL_pred", "PL_pred (<1e8 abs)", "#7c3aed", True),
        ],
        True,
    )
    if not phase2_series_values(online_rows, ["PL_pred"], True):
        body.append(svg_text(90, 412, "PL_pred is sentinel-scale/unbounded in this run, so the plot omits it from the zoomed meter range.", 12, "#4b5563"))

    add_panel(
        70.0,
        640.0,
        990.0,
        210.0,
        "Offline alignment error",
        "meters / seconds",
        [
            (aligned_rows, "spatial_tracking_error", "tracking error [m]", "#2563eb", False),
            (aligned_rows, "estimation_error", "estimation error [m]", "#7c3aed", False),
            (aligned_rows, "time_alignment_error_s", "time alignment [s]", "#64748b", False),
        ],
        True,
    )
    write_svg(path, width, height, body)


def generate_phase2_prediction_xy_svg(analysis: dict[str, Any], path: Path) -> None:
    width, height = 900, 760
    body: list[str] = [svg_text(40, 34, "Phase 2 Predicted Samples vs Executed Path", 18, "#111827")]
    online_rows = analysis.get("online_rows", [])
    aligned_rows = analysis.get("rows", [])
    pred_points = [
        row for row in online_rows
        if to_float(row.get("x")) is not None and to_float(row.get("y")) is not None
    ]
    truth_points = [
        row for row in aligned_rows
        if to_float(row.get("executed_truth_x")) is not None and to_float(row.get("executed_truth_y")) is not None
    ]
    iap_points = [
        row for row in aligned_rows
        if to_float(row.get("executed_iap_x")) is not None and to_float(row.get("executed_iap_y")) is not None
    ]
    if not pred_points:
        body.append(svg_text(40, 80, "No predicted XY samples were available.", 14, "#991b1b"))
        write_svg(path, width, height, body)
        return

    xs = [float(to_float(row["x"]) or 0.0) for row in pred_points]
    ys = [float(to_float(row["y"]) or 0.0) for row in pred_points]
    xs.extend(float(to_float(row["executed_truth_x"]) or 0.0) for row in truth_points)
    ys.extend(float(to_float(row["executed_truth_y"]) or 0.0) for row in truth_points)
    xs.extend(float(to_float(row["executed_iap_x"]) or 0.0) for row in iap_points)
    ys.extend(float(to_float(row["executed_iap_y"]) or 0.0) for row in iap_points)
    x0, x1 = float_range(xs)
    y0, y1 = float_range(ys)
    px, py, pw, ph = 70.0, 80.0, 760.0, 560.0
    body.extend(svg_axes(px, py, pw, ph, "XY path", "x [m]", "y [m]"))

    def xy(row: dict[str, Any], x_key: str, y_key: str) -> tuple[float, float]:
        x = map_linear(float(to_float(row[x_key]) or 0.0), x0, x1, px, px + pw)
        y = map_linear(float(to_float(row[y_key]) or 0.0), y0, y1, py + ph, py)
        return x, y

    if truth_points:
        body.append(svg_polyline([xy(row, "executed_truth_x", "executed_truth_y") for row in truth_points], "#111827", 2.0, 0.9))
    if iap_points:
        body.append(svg_polyline([xy(row, "executed_iap_x", "executed_iap_y") for row in iap_points], "#2563eb", 1.5, 0.72))

    stride = max(1, len(pred_points) // 900)
    for row in pred_points[::stride]:
        x, y = xy(row, "x", "y")
        body.append(
            f'<circle cx="{x:.2f}" cy="{y:.2f}" r="2.8" '
            f'fill="{phase2_risk_color(row.get("risk_state_pred"))}" fill-opacity="0.65" />'
        )

    predicted = analysis.get("predicted_integrity", {})
    actual = analysis.get("actual_alignment", {})
    legend = [
        ("executed truth", "#111827"),
        ("executed IAP estimate", "#2563eb"),
        ("SAFE_PRED", phase2_risk_color("SAFE_PRED")),
        ("MARGINAL_PRED", phase2_risk_color("MARGINAL_PRED")),
        ("UNSAFE_PRED", phase2_risk_color("UNSAFE_PRED")),
    ]
    for idx, (label, color) in enumerate(legend):
        y = 675 + idx * 18
        body.append(f'<circle cx="92" cy="{y - 4:.2f}" r="4.0" fill="{color}" fill-opacity="0.8" />')
        body.append(svg_text(108, y, label, 12, "#374151"))
    body.append(svg_text(330, 676, f"risk counts={predicted.get('risk_state_counts', {})}", 12, "#111827"))
    body.append(svg_text(330, 700, f"mean tracking error={phase2_display_number(actual.get('mean_spatial_tracking_error'))} m", 12, "#111827"))
    body.append(svg_text(px - 10, py + ph + 4, f"{y0:.2f}", 10, "#4b5563", "end"))
    body.append(svg_text(px - 10, py + 4, f"{y1:.2f}", 10, "#4b5563", "end"))
    write_svg(path, width, height, body)


def generate_phase2_pred_actual_comparison_svg(analysis: dict[str, Any], path: Path) -> None:
    width, height = 1120, 820
    body: list[str] = [svg_text(40, 34, "Phase 2 Predicted vs Actual Integrity Comparison", 18, "#111827")]
    rows = phase2_sorted_by_time(analysis.get("rows", []), "sample_abs_time")
    if not rows:
        body.append(svg_text(40, 80, "No aligned Phase 2 rows were available.", 14, "#991b1b"))
        write_svg(path, width, height, body)
        return
    t0, t1 = phase2_time_bounds(rows, "sample_abs_time")
    rel_label = f"relative time from {t0:.3f}s"

    def add_error_timeline(px: float, py: float, pw: float, ph: float, title: str, key: str, color: str) -> None:
        values = phase2_series_values(rows, [key], False)
        y0, y1 = float_range(values)
        y0 = min(y0, 0.0)
        y1 = max(y1, 0.0)
        body.extend(svg_axes(px, py, pw, ph, title, rel_label, "pred - actual"))
        zero_y = map_linear(0.0, y0, y1, py + ph, py)
        body.append(f'<line x1="{px:.2f}" y1="{zero_y:.2f}" x2="{px + pw:.2f}" y2="{zero_y:.2f}" stroke="#9ca3af" stroke-dasharray="5 4" />')
        body.append(svg_polyline(phase2_time_points(rows, "sample_abs_time", key, px, py, pw, ph, t0, t1, y0, y1), color, 1.9, 0.92))
        body.append(svg_text_bg(px + 12, py + ph - 12, f"mean={phase2_display_number(phase2_mean([row.get(key) for row in rows]))}", 12, "#111827", "start", 0.82))
        body.append(svg_text(px - 10, py + ph + 4, f"{y0:.2f}", 10, "#4b5563", "end"))
        body.append(svg_text(px - 10, py + 4, f"{y1:.2f}", 10, "#4b5563", "end"))

    def add_scatter(px: float, py: float, pw: float, ph: float, title: str, pred_key: str, actual_key: str) -> None:
        paired = []
        for row in rows:
            pred = phase2_usable_plot_value(row.get(pred_key))
            actual = phase2_usable_plot_value(row.get(actual_key))
            if pred is not None and actual is not None:
                paired.append((pred, actual, row))
        body.extend(svg_axes(px, py, pw, ph, title, "predicted [m]", "actual [m]"))
        if not paired:
            body.append(svg_text(px + 20, py + 42, "No non-sentinel paired values.", 13, "#991b1b"))
            return
        values = [value for pred, actual, _row in paired for value in (pred, actual)]
        lo, hi = float_range(values)
        lo = min(0.0, lo)
        p0 = (map_linear(lo, lo, hi, px, px + pw), map_linear(lo, lo, hi, py + ph, py))
        p1 = (map_linear(hi, lo, hi, px, px + pw), map_linear(hi, lo, hi, py + ph, py))
        body.append(f'<line x1="{p0[0]:.2f}" y1="{p0[1]:.2f}" x2="{p1[0]:.2f}" y2="{p1[1]:.2f}" stroke="#6b7280" stroke-dasharray="5 4" />')
        stride = max(1, len(paired) // 700)
        for pred, actual, row in paired[::stride]:
            x = map_linear(pred, lo, hi, px, px + pw)
            y = map_linear(actual, lo, hi, py + ph, py)
            color = "#16a34a" if row.get("same_safe_unsafe_label") == "true" else "#dc2626"
            body.append(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="3.0" fill="{color}" fill-opacity="0.7" />')
        body.append(svg_text_bg(px + 12, py + ph - 12, f"paired={len(paired)}", 12, "#111827", "start", 0.82))
        body.append(svg_text(px - 10, py + ph + 4, f"{lo:.2f}", 10, "#4b5563", "end"))
        body.append(svg_text(px - 10, py + 4, f"{hi:.2f}", 10, "#4b5563", "end"))

    add_error_timeline(70.0, 80.0, 450.0, 250.0, "PL prediction error", "pred_actual_PL_error", "#2563eb")
    add_error_timeline(610.0, 80.0, 450.0, 250.0, "IM prediction error", "pred_actual_IM_error", "#dc2626")
    add_scatter(70.0, 440.0, 450.0, 270.0, "Predicted PL vs actual PL", "pred_PL", "actual_PL")
    add_scatter(610.0, 440.0, 450.0, 270.0, "Predicted IM vs actual IM", "pred_IM", "actual_IM")
    write_svg(path, width, height, body)


def generate_phase2_truth_pi_hvpl_comparison_svg(
    phase2_analysis: dict[str, Any],
    truth_analysis: dict[str, Any],
    source: str,
    path: Path,
) -> None:
    label = "GNSS" if source == "gnss" else "LiDAR"
    width, height = 1120, 820
    body: list[str] = [
        svg_text(40, 34, f"Phase 2 PI Prediction vs Truth-Pose {label} ARAIM HPL/VPL", 18, "#111827")
    ]
    tolerance_s = float(to_float(phase2_analysis.get("match_tolerance_s")) or 0.10)
    rows = phase2_truth_pi_aligned_rows(phase2_analysis, truth_analysis, source, tolerance_s)
    if not phase2_analysis.get("available"):
        body.append(svg_text(40, 80, "Phase 2 prediction analysis is unavailable.", 14, "#991b1b"))
        write_svg(path, width, height, body)
        return
    if not truth_analysis.get("available"):
        body.append(svg_text(40, 80, "Truth-pose ARAIM baseline CSV is unavailable.", 14, "#991b1b"))
        body.append(svg_text(40, 106, "Run demo10 again so export/demo10_araim_truth_compare.csv is produced.", 12, "#4b5563"))
        write_svg(path, width, height, body)
        return
    if not rows:
        body.append(svg_text(40, 80, f"No paired {label} truth baseline and PI prediction rows within {tolerance_s:.3f}s.", 14, "#991b1b"))
        body.append(svg_text(40, 106, "PI prediction uses Phase2 PL_H_pred/PL_V_pred; truth baseline uses truth-pose ARAIM HPL/VPL.", 12, "#4b5563"))
        write_svg(path, width, height, body)
        return

    t0, t1 = phase2_time_bounds(rows, "sample_abs_time")
    rel_label = f"relative time from {t0:.3f}s"

    def valid_pairs(pred_key: str, truth_key: str) -> list[dict[str, Any]]:
        return [
            row
            for row in rows
            if to_float(row.get(pred_key)) is not None and to_float(row.get(truth_key)) is not None
        ]

    def add_timeline(
        px: float,
        py: float,
        pw: float,
        ph: float,
        title: str,
        pred_key: str,
        truth_key: str,
        delta_key: str,
    ) -> None:
        panel_rows = valid_pairs(pred_key, truth_key)
        body.extend(svg_axes(px, py, pw, ph, title, rel_label, "meters"))
        if not panel_rows:
            body.append(svg_text(px + 20, py + 42, "No paired finite values.", 13, "#991b1b"))
            return
        values = phase2_series_values(panel_rows, [pred_key, truth_key], True)
        y0, y1 = float_range(values)
        y0 = min(0.0, y0)
        body.append(svg_polyline(phase2_time_points(panel_rows, "sample_abs_time", truth_key, px, py, pw, ph, t0, t1, y0, y1, True), "#0891b2", 2.1, 0.95))
        body.append(svg_polyline(phase2_time_points(panel_rows, "sample_abs_time", pred_key, px, py, pw, ph, t0, t1, y0, y1, True), "#7c3aed", 1.9, 0.92))
        deltas = [to_float(row.get(delta_key)) for row in panel_rows if to_float(row.get(delta_key)) is not None]
        mean_delta = sum(deltas) / len(deltas) if deltas else math.nan
        under_count = sum(1 for row in panel_rows if float(row[pred_key]) < float(row[truth_key]))
        body.append(svg_text_bg(px + 12, py + ph - 34, f"paired={len(panel_rows)}, PI<truth={under_count}, mean(PI-truth)={phase2_display_number(mean_delta)}m", 12, "#111827", "start", 0.82))
        body.append(svg_text_bg(px + 12, py + ph - 14, f"mean match dt={phase2_display_number(phase2_mean([row.get('match_dt_s') for row in panel_rows]))}s", 12, "#4b5563", "start", 0.82))
        body.extend(svg_legend_group(px + pw - 220, py + 22, [
            (f"truth-pose {label}", "#0891b2"),
            ("PI predicted", "#7c3aed"),
        ], item_h=20.0))
        body.append(svg_text(px - 10, py + ph + 4, f"{y0:.2f}", 10, "#4b5563", "end"))
        body.append(svg_text(px - 10, py + 4, f"{y1:.2f}", 10, "#4b5563", "end"))

    def add_scatter(
        px: float,
        py: float,
        pw: float,
        ph: float,
        title: str,
        pred_key: str,
        truth_key: str,
    ) -> None:
        paired = valid_pairs(pred_key, truth_key)
        body.extend(svg_axes(px, py, pw, ph, title, "truth-pose baseline [m]", "PI predicted [m]"))
        if not paired:
            body.append(svg_text(px + 20, py + 42, "No paired finite values.", 13, "#991b1b"))
            return
        values = []
        for row in paired:
            values.extend([float(row[truth_key]), float(row[pred_key])])
        lo, hi = float_range(values)
        lo = min(0.0, lo)
        p0 = (map_linear(lo, lo, hi, px, px + pw), map_linear(lo, lo, hi, py + ph, py))
        p1 = (map_linear(hi, lo, hi, px, px + pw), map_linear(hi, lo, hi, py + ph, py))
        body.append(f'<line x1="{p0[0]:.2f}" y1="{p0[1]:.2f}" x2="{p1[0]:.2f}" y2="{p1[1]:.2f}" stroke="#6b7280" stroke-dasharray="5 4" />')
        stride = max(1, len(paired) // 800)
        for row in paired[::stride]:
            truth = float(row[truth_key])
            pred = float(row[pred_key])
            color = "#16a34a" if pred >= truth else "#dc2626"
            x = map_linear(truth, lo, hi, px, px + pw)
            y = map_linear(pred, lo, hi, py + ph, py)
            body.append(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="3.0" fill="{color}" fill-opacity="0.72" />')
        body.append(svg_text_bg(px + 12, py + ph - 12, f"green: PI>=truth, red: PI<truth, paired={len(paired)}", 12, "#111827", "start", 0.82))
        body.append(svg_text(px - 10, py + ph + 4, f"{lo:.2f}", 10, "#4b5563", "end"))
        body.append(svg_text(px - 10, py + 4, f"{hi:.2f}", 10, "#4b5563", "end"))

    add_timeline(70.0, 80.0, 990.0, 210.0, f"{label} HPL timeline", "pred_HPL", "truth_HPL", "delta_HPL")
    add_timeline(70.0, 360.0, 990.0, 210.0, f"{label} VPL timeline", "pred_VPL", "truth_VPL", "delta_VPL")
    add_scatter(70.0, 660.0, 450.0, 120.0, f"{label} HPL scatter", "pred_HPL", "truth_HPL")
    add_scatter(610.0, 660.0, 450.0, 120.0, f"{label} VPL scatter", "pred_VPL", "truth_VPL")
    body.append(svg_text(70, 810, "Note: current PI-lite PL_H_pred/PL_V_pred are source-agnostic predictions from /iap/integrity, compared against source-specific truth-pose baselines.", 12, "#4b5563"))
    write_svg(path, width, height, body)


