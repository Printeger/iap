def phase2_shorten(value: Any, max_len: int = 74) -> str:
    text = str(value)
    if len(text) <= max_len:
        return text
    return text[: max(0, max_len - 3)] + "..."


def phase2_value_status(value: Any, sentinel_abs: float = PHASE2_SENTINEL_ABS) -> tuple[str, float | None]:
    if value is None:
        return "missing", None
    text = str(value).strip()
    if text == "":
        return "missing", None
    try:
        number = float(text)
    except ValueError:
        return "nonnumeric", None
    if not math.isfinite(number):
        return "nonfinite", None
    if abs(number) >= sentinel_abs:
        return "sentinel", number
    return "usable", number


def phase2_column_profile(
    rows: list[dict[str, Any]],
    keys: list[str],
    sentinel_abs: float = PHASE2_SENTINEL_ABS,
) -> list[dict[str, Any]]:
    profiles: list[dict[str, Any]] = []
    for key in keys:
        counts = Counter()
        samples = Counter()
        for row in rows:
            exists = key in row
            if not exists:
                counts["missing_column"] += 1
                continue
            status, _number = phase2_value_status(row.get(key), sentinel_abs)
            counts[status] += 1
            raw = row.get(key)
            if raw not in (None, "") and len(samples) < 6:
                samples[str(raw)] += 1
        profiles.append({
            "key": key,
            "exists": any(key in row for row in rows),
            "usable": counts.get("usable", 0),
            "nonfinite": counts.get("nonfinite", 0),
            "sentinel": counts.get("sentinel", 0),
            "nonnumeric": counts.get("nonnumeric", 0),
            "missing": counts.get("missing", 0) + counts.get("missing_column", 0),
            "sample": ", ".join(value for value, _count in samples.most_common(3)),
        })
    return profiles


def phase2_first_usable_with_status(
    row: dict[str, Any],
    keys: list[str],
    sentinel_abs: float = PHASE2_SENTINEL_ABS,
) -> tuple[float | None, str, str]:
    fallback_status = "missing_column"
    fallback_key = keys[0] if keys else ""
    priority = {"sentinel": 4, "nonfinite": 3, "nonnumeric": 2, "missing": 1, "missing_column": 0}
    best_priority = -1
    for key in keys:
        if key not in row:
            continue
        status, number = phase2_value_status(row.get(key), sentinel_abs)
        if status == "usable":
            return number, "usable", key
        rank = priority.get(status, 0)
        if rank > best_priority:
            best_priority = rank
            fallback_status = status
            fallback_key = key
    return None, fallback_status, fallback_key


def phase2_pair_diagnostics(
    rows: list[dict[str, Any]],
    x_keys: list[str],
    y_keys: list[str],
    sentinel_abs: float = PHASE2_SENTINEL_ABS,
) -> dict[str, Any]:
    reasons = Counter()
    paired = 0
    for row in rows:
        x, x_status, x_key = phase2_first_usable_with_status(row, x_keys, sentinel_abs)
        y, y_status, y_key = phase2_first_usable_with_status(row, y_keys, sentinel_abs)
        if x is not None and y is not None:
            paired += 1
            continue
        if x is None:
            reasons[f"x:{x_key}:{x_status}"] += 1
        if y is None:
            reasons[f"y:{y_key}:{y_status}"] += 1
    return {
        "rows": len(rows),
        "paired": paired,
        "x_profiles": phase2_column_profile(rows, x_keys, sentinel_abs),
        "y_profiles": phase2_column_profile(rows, y_keys, sentinel_abs),
        "missing_reasons": dict(reasons.most_common(8)),
    }


