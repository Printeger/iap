def generate_phase2_conservative_fusion_svg(
    phase2_analysis: dict[str, Any],
    pred_rows: list[dict[str, str]],
    path: Path,
) -> None:
    width, height = 1220, 900
    body: list[str] = [svg_text(40, 34, "Conservative Fused FIM Check", 18, "#111827")]
    lidar_summary = phase2_analysis.get("lidar_observability") or {}
    fused_enabled = phase2_analysis.get("pl_model") == "fused_fim_grid" or boolish(lidar_summary.get("fused_fim_grid")) is True
    body.append(svg_text(40, 58, f"fused_fim_grid_enabled={fused_enabled}; source=export/integrity_along_planner_traj.csv", 12, "#4b5563"))
    if not pred_rows:
        body.append(svg_text(40, 90, "No future predictor rows were available.", 14, "#991b1b"))
        write_svg(path, width, height, body)
        return
    # Inline scatter keeps this check readable without changing the generic scatter file shape.
    paired = []
    for row in pred_rows:
        gnss = phase2_usable_plot_value(row.get("gnss_hpl"))
        fused = phase2_usable_plot_value(row.get("fused_hpl"))
        if gnss is not None and fused is not None:
            paired.append((gnss, fused, row))
    px, py, pw, ph = 70.0, 95.0, 440.0, 270.0
    body.extend(svg_axes(px, py, pw, ph, "gnss_hpl vs fused_hpl", "gnss_hpl [m]", "fused_hpl [m]"))
    if paired:
        values = [v for gnss, fused, _row in paired for v in (gnss, fused)]
        lo, hi = float_range(values)
        lo = min(0.0, lo)
        body.append(svg_line(map_linear(lo, lo, hi, px, px + pw), map_linear(lo, lo, hi, py + ph, py), map_linear(hi, lo, hi, px, px + pw), map_linear(hi, lo, hi, py + ph, py), "#6b7280", 1.1, 0.75, "5 4"))
        for gnss, fused, row in paired[::max(1, len(paired) // 800)]:
            x = map_linear(gnss, lo, hi, px, px + pw)
            y = map_linear(fused, lo, hi, py + ph, py)
            body.append(svg_circle(x, y, 2.8, "#2563eb", 0.72))
        body.append(svg_text_bg(px + 12, py + ph - 12, f"paired={len(paired)}", 12, "#111827", "start", 0.82))
    else:
        diagnostics = phase2_pair_diagnostics(pred_rows, ["gnss_hpl"], ["fused_hpl"])
        body.append(svg_text(px + 18, py + 42, f"No paired values: {diagnostics['missing_reasons']}", 12, "#991b1b"))
    add_phase2_series_panel(
        body, pred_rows, "sample_abs_time",
        [("gnss_hpl", "gnss_hpl", "#2563eb"), ("fused_hpl", "fused_hpl", "#f97316"), ("PL_H_pred", "PL_H_pred", "#111827")],
        590.0, 95.0, 540.0, 270.0, "HPL conservative envelope inputs", "meters",
    )
    deltas_h: list[float] = []
    deltas_v: list[float] = []
    violations_h = 0
    violations_v = 0
    for row in pred_rows:
        pl_h = phase2_usable_plot_value(row.get("PL_H_pred"))
        pl_v = phase2_usable_plot_value(row.get("PL_V_pred"))
        gnss_h = phase2_usable_plot_value(row.get("gnss_hpl"))
        gnss_v = phase2_usable_plot_value(row.get("gnss_vpl"))
        if pl_h is not None and gnss_h is not None:
            delta = pl_h - gnss_h
            deltas_h.append(delta)
            if delta < -1.0e-6:
                violations_h += 1
        if pl_v is not None and gnss_v is not None:
            delta = pl_v - gnss_v
            deltas_v.append(delta)
            if delta < -1.0e-6:
                violations_v += 1
    delta_rows = []
    for row in pred_rows:
        item = dict(row)
        pl_h = phase2_usable_plot_value(row.get("PL_H_pred"))
        pl_v = phase2_usable_plot_value(row.get("PL_V_pred"))
        gnss_h = phase2_usable_plot_value(row.get("gnss_hpl"))
        gnss_v = phase2_usable_plot_value(row.get("gnss_vpl"))
        item["delta_PL_H_minus_gnss_hpl"] = pl_h - gnss_h if pl_h is not None and gnss_h is not None else math.nan
        item["delta_PL_V_minus_gnss_vpl"] = pl_v - gnss_v if pl_v is not None and gnss_v is not None else math.nan
        delta_rows.append(item)
    add_phase2_series_panel(
        body, delta_rows, "sample_abs_time",
        [("delta_PL_H_minus_gnss_hpl", "PL_H_pred - gnss_hpl", "#2563eb"), ("delta_PL_V_minus_gnss_vpl", "PL_V_pred - gnss_vpl", "#7c3aed")],
        70.0, 470.0, 1060.0, 230.0, "Conservative margin vs GNSS", "meters", False,
    )
    verdict = "PASS: no official PL below GNSS PL" if violations_h == 0 and violations_v == 0 else "FAIL: fused official PL below GNSS PL"
    verdict_color = "#166534" if violations_h == 0 and violations_v == 0 else "#991b1b"
    body.append(svg_text(70, 770, verdict, 15, verdict_color))
    body.append(svg_text(70, 798, f"H violations={violations_h}, V violations={violations_v}, H paired={len(deltas_h)}, V paired={len(deltas_v)}", 12, "#111827"))
    if not fused_enabled:
        body.append(svg_text(70, 826, "Mode is not fused_fim_grid in this run; the check is still computed from available debug columns.", 12, "#4b5563"))
    write_svg(path, width, height, body)


def generate_phase2_prediction_fan_svg(
    phase2_analysis: dict[str, Any],
    path: Path,
) -> None:
    width, height = 1120, 900
    body: list[str] = [svg_text(40, 34, "Phase 2 Prediction Horizon Fan", 18, "#111827")]
    rows = phase2_sorted_by_time(phase2_analysis.get("online_rows", []), "sample_abs_time")
    if not rows:
        body.append(svg_text(40, 80, "No Phase 2 prediction rows were available.", 14, "#991b1b"))
        write_svg(path, width, height, body)
        return

    grouped = phase2_group_rows(rows, "traj_id")
    traces = []
    for traj_id, traj_rows in grouped.items():
        future_points = []
        for row in phase2_sorted_by_time(traj_rows, "sample_t_from_now"):
            t = to_float(row.get("sample_t_from_now"))
            if t is None or t < 0.0:
                continue
            future_points.append(row)
        if len(future_points) >= 2:
            traces.append((traj_id, future_points))
    if not traces:
        body.append(svg_text(40, 80, "No replanning traces with future horizon samples were available.", 14, "#991b1b"))
        write_svg(path, width, height, body)
        return

    traces.sort(key=lambda item: float(to_float(item[1][0].get("sample_abs_time")) or 0.0))
    if len(traces) > 50:
        step = max(1, len(traces) // 50)
        traces = traces[::step][:50]

    stamp_values = [float(to_float(trace[1][0].get("sample_abs_time")) or 0.0) for trace in traces]
    stamp_lo, stamp_hi = float_range(stamp_values)
    max_horizon = 5.0
    horizon_values = []
    for _traj_id, trace_rows in traces:
        for row in trace_rows:
            t = to_float(row.get("sample_t_from_now"))
            if t is not None and 0.0 <= t <= max_horizon:
                horizon_values.append(t)
    if horizon_values:
        max_horizon = max(5.0, max(horizon_values))

    panels = [
        (70.0, 80.0, 990.0, 210.0, "Future HPL fan", "PL_H_pred", "HPL [m]"),
        (70.0, 360.0, 990.0, 210.0, "Future VPL fan", "PL_V_pred", "VPL [m]"),
        (70.0, 640.0, 990.0, 210.0, "Future IM fan", "IM_pred", "IM [m]"),
    ]
    for px, py, pw, ph, title, value_key, ylabel in panels:
        panel_values = []
        for _traj_id, trace_rows in traces:
            for row in trace_rows:
                value = phase2_usable_plot_value(row.get(value_key))
                if value is not None:
                    panel_values.append(value)
        y0, y1 = float_range(panel_values)
        body.extend(svg_axes(px, py, pw, ph, title, "lookahead time [s]", ylabel))
        body.append(svg_line(px, py + ph, px + pw, py, "#6b7280", 1.0, 0.4, "4 4"))
        for traj_id, trace_rows in traces:
            trace_stamp = float(to_float(trace_rows[0].get("sample_abs_time")) or 0.0)
            color = phase2_value_color(trace_stamp, stamp_lo, stamp_hi)
            points = []
            for row in trace_rows:
                t = to_float(row.get("sample_t_from_now"))
                value = phase2_usable_plot_value(row.get(value_key))
                if t is None or value is None or t < 0.0 or t > max_horizon:
                    continue
                x = map_linear(t, 0.0, max_horizon, px, px + pw)
                y = map_linear(value, y0, y1, py + ph, py)
                points.append((x, y))
            if len(points) >= 2:
                body.append(svg_polyline(points, color, 1.4, 0.16))
        body.append(svg_text_bg(px + 12, py + ph - 12, f"traces={len(traces)}, horizon={max_horizon:.1f}s", 12, "#111827", "start", 0.82))
        body.append(svg_text(px - 10, py + ph + 4, f"{y0:.2f}", 10, "#4b5563", "end"))
        body.append(svg_text(px - 10, py + 4, f"{y1:.2f}", 10, "#4b5563", "end"))

    body.append(svg_text(70, 870, "Each line is one replan trace; color transitions from early to late replanning times.", 12, "#4b5563"))
    write_svg(path, width, height, body)


