#!/usr/bin/env python3
"""
Run-scoped log analyzer for the current IAP logging layout.

Default input:
  src/iap/log/latest

Supported layout:
  runtime/*.log
  profiling/iap_timing.csv
  export/iap_icp.csv
  export/iap_gnss_factor_debug.csv
  export/iap_araim.csv
  export/traj_with_gnss.csv
  export/dump/*
  metadata/run_info.json
  metadata/config/*.json

The old CT/frontend-only artifacts were intentionally removed from this
analyzer. This script reports only artifacts that exist in the new run-scoped
logging contract.
"""

