def timeline_points(
    rows: list[dict[str, Any]],
    value_key: str,
    plot_x: float,
    plot_y: float,
    plot_w: float,
    plot_h: float,
    t0: float,
    t1: float,
    y0: float,
    y1: float,
) -> list[tuple[float, float]]:
    points = []
    for row in rows:
        stamp = float(row["stamp"])
        value = float(row[value_key])
        x = map_linear(stamp, t0, t1, plot_x, plot_x + plot_w)
        y = map_linear(value, y0, y1, plot_y + plot_h, plot_y)
        points.append((x, y))
    return points


