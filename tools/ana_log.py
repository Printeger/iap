def float_range(values: list[float], pad_ratio: float = 0.08) -> tuple[float, float]:
    finite = [value for value in values if math.isfinite(value)]
    if not finite:
        return 0.0, 1.0
    lo = min(finite)
    hi = max(finite)
    if math.isclose(lo, hi):
        delta = max(abs(lo) * 0.1, 1.0)
        return lo - delta, hi + delta
    pad = (hi - lo) * pad_ratio
    return lo - pad, hi + pad


def map_linear(value: float, src_lo: float, src_hi: float, dst_lo: float, dst_hi: float) -> float:
    if math.isclose(src_lo, src_hi):
        return (dst_lo + dst_hi) * 0.5
    alpha = (value - src_lo) / (src_hi - src_lo)
    return dst_lo + alpha * (dst_hi - dst_lo)


def svg_polyline(points: list[tuple[float, float]], color: str, width: float = 1.6, opacity: float = 1.0) -> str:
    if len(points) < 2:
        return ""
    point_text = " ".join(f"{x:.2f},{y:.2f}" for x, y in points)
    return (
        f'<polyline points="{point_text}" fill="none" stroke="{color}" '
        f'stroke-width="{width:.2f}" stroke-opacity="{opacity:.3f}" />'
    )


def svg_text(x: float, y: float, text: Any, size: int = 12, color: str = "#1f2937", anchor: str = "start") -> str:
    return (
        f'<text x="{x:.2f}" y="{y:.2f}" font-family="monospace" font-size="{size}" '
        f'fill="{color}" text-anchor="{anchor}">{html.escape(str(text))}</text>'
    )


def svg_axes(
    x: float,
    y: float,
    w: float,
    h: float,
    title: str,
    x_label: str,
    y_label: str,
) -> list[str]:
    return [
        f'<rect x="{x:.2f}" y="{y:.2f}" width="{w:.2f}" height="{h:.2f}" fill="#ffffff" stroke="#d1d5db" />',
        f'<line x1="{x:.2f}" y1="{y + h:.2f}" x2="{x + w:.2f}" y2="{y + h:.2f}" stroke="#374151" />',
        f'<line x1="{x:.2f}" y1="{y:.2f}" x2="{x:.2f}" y2="{y + h:.2f}" stroke="#374151" />',
        svg_text(x + w * 0.5, y - 14, title, 14, "#111827", "middle"),
        svg_text(x + w * 0.5, y + h + 32, x_label, 11, "#4b5563", "middle"),
        svg_text(x - 10, y + 14, y_label, 11, "#4b5563", "end"),
    ]


def svg_text_bg(
    x: float,
    y: float,
    text: Any,
    size: int = 12,
    color: str = "#1f2937",
    anchor: str = "start",
    bg_opacity: float = 0.0,
) -> str:
    """svg_text with optional semi-transparent white background to keep text
    readable when curves pass through it."""
    result = svg_text(x, y, text, size, color, anchor)
    if bg_opacity <= 0.0:
        return result
    # Rough width estimate: monospace font, average char width ≈ size * 0.6
    text_str = html.escape(str(text))
    est_w = len(text_str) * size * 0.6
    est_h = size * 1.3
    x0 = x if anchor == "start" else (x - est_w if anchor == "end" else x - est_w * 0.5)
    y0 = y - size * 0.9
    bg = (
        f'<rect x="{x0:.2f}" y="{y0:.2f}" width="{est_w:.2f}" height="{est_h:.2f}" '
        f'fill="#ffffff" fill-opacity="{bg_opacity:.2f}" rx="2" />'
    )
    return bg + result


def svg_legend_group(
    x: float,
    y: float,
    items: list[tuple[str, str]],
    line_w: float = 25.0,
    font_size: int = 11,
    item_h: float = 18.0,
) -> list[str]:
    """Draw legend items with a semi-transparent white background so they stay
    readable even when plot curves pass behind them."""
    if not items:
        return []
    n = len(items)
    pad_x = 8.0
    pad_y = 6.0
    # Estimate width: line_w + gap + max label width
    max_label_chars = max(len(label) for label, _ in items)
    est_w = line_w + 12 + max_label_chars * font_size * 0.6 + pad_x * 2
    est_h = n * item_h + pad_y * 2
    x0 = x - pad_x
    y0 = y - pad_y - font_size * 0.9
    parts = [
        f'<rect x="{x0:.2f}" y="{y0:.2f}" width="{est_w:.2f}" height="{est_h:.2f}" '
        f'fill="#ffffff" fill-opacity="0.82" stroke="#d1d5db" stroke-opacity="0.5" rx="3" />'
    ]
    for idx, (label, color) in enumerate(items):
        ly = y + idx * item_h
        parts.append(
            f'<line x1="{x:.2f}" y1="{ly:.2f}" x2="{x + line_w:.2f}" y2="{ly:.2f}" '
            f'stroke="{color}" stroke-width="2.2" />'
        )
        parts.append(svg_text(x + line_w + 8, ly + font_size * 0.35, label, font_size, "#374151"))
    return parts


def state_color(state: Any) -> str:
    state_text = str(state).upper()
    if state_text == "SAFE":
        return "#16a34a"
    if state_text == "SAFE_EXCLUDED":
        return "#eab308"
    if state_text == "UNSAFE":
        return "#dc2626"
    return "#6b7280"


