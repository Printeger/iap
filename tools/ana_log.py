PACKAGE_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RUN = PACKAGE_ROOT / "log" / "latest"

RUNTIME_LOG_RE = re.compile(
    r"^\[(?P<ts>[^\]]+)\]\s+\[(?P<logger>[^\]]+)\]\s+\[(?P<level>[^\]]+)\]\s+(?P<message>.*)$"
)
NUMBER_RE = re.compile(r"\b\d+(?:\.\d+)?\b")


@dataclass
class ArtifactStatus:
    name: str
    rel_path: str
    status: str
    reason: str
    rows: int | None = None
    size_bytes: int = 0
    note: str = ""


