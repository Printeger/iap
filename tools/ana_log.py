def phase2_truth_pi_aligned_rows(
    phase2_analysis: dict[str, Any],
    truth_analysis: dict[str, Any],
    source: str,
    tolerance_s: float,
) -> list[dict[str, Any]]:
    pred_rows = phase2_sorted_by_time(phase2_analysis.get("online_rows", []), "sample_abs_time")
    truth_rows = [
        row
        for row in truth_analysis.get("rows", [])
        if to_float(row.get("stamp")) is not None
    ]
    if not pred_rows or not truth_rows:
        return []

    truth_index = phase2_build_index(truth_rows, "stamp")
    aligned: list[dict[str, Any]] = []
    for pred in pred_rows:
        sample_time = to_float(pred.get("sample_abs_time"))
        if sample_time is None:
            continue
        truth, dt = phase2_nearest(truth_index, sample_time, tolerance_s)
        if truth is None:
            continue
