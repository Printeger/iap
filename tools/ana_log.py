    y0 = min(0.0, y0)
    drew = False
    legend_items: list[tuple[str, str]] = []
    for idx, (key, label, color) in enumerate(series):
        points = phase2_time_points(timed_rows, time_key, key, px, py, pw, ph, t0, t1, y0, y1, skip_sentinel)
        if points:
            body.append(svg_polyline(points, color, 1.8, 0.92))
            drew = True
