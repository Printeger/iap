def analyze_trajectory(rows: list[dict[str, str]]) -> dict[str, Any]:
    if not rows:
        return {"available": False}
    stamps = numeric_values_any(rows, ["stamp", "timestamp", "time"])
    xs = numeric_values(rows, "x")
    ys = numeric_values(rows, "y")
    zs = numeric_values(rows, "z")
    span_s = max(stamps) - min(stamps) if len(stamps) >= 2 else 0.0
    path_length = 0.0
    points = []
    for row in rows:
        x, y, z = to_float(row.get("x")), to_float(row.get("y")), to_float(row.get("z"))
        if x is not None and y is not None and z is not None:
            points.append((x, y, z))
    for prev, cur in zip(points, points[1:]):
        path_length += math.sqrt(sum((cur[i] - prev[i]) ** 2 for i in range(3)))
    return {
        "available": True,
        "row_count": len(rows),
        "span_s": span_s,
        "path_length_m": path_length,
        "x": stats(xs),
        "y": stats(ys),
        "z": stats(zs),
    }


