def phase2_display_number(value: Any, digits: int = 3) -> str:
    number = to_float(value)
    if number is None:
        return "n/a"
    if abs(number) >= PHASE2_SENTINEL_ABS:
        return f"{number:.3e}"
    return f"{number:.{digits}f}"


def phase2_risk_color(state: Any) -> str:
    state_text = str(state).upper()
    if state_text in {"SAFE", "SAFE_PRED"}:
        return "#16a34a"
    if state_text in {"MARGINAL", "MARGINAL_PRED", "SAFE_EXCLUDED"}:
        return "#eab308"
    if state_text in {"UNSAFE", "UNSAFE_PRED"}:
        return "#dc2626"
    return "#6b7280"


def phase2_sorted_by_time(rows: list[dict[str, Any]], time_key: str) -> list[dict[str, Any]]:
    return sorted(
        [row for row in rows if to_float(row.get(time_key)) is not None],
        key=lambda row: float(to_float(row.get(time_key)) or 0.0),
    )


def phase2_time_bounds(rows: list[dict[str, Any]], time_key: str) -> tuple[float, float]:
    times = [float(to_float(row.get(time_key)) or 0.0) for row in rows if to_float(row.get(time_key)) is not None]
    if not times:
        return 0.0, 1.0
    t0, t1 = min(times), max(times)
    if math.isclose(t0, t1):
        return t0, t0 + 1.0
    return t0, t1


