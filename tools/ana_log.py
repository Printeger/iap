def phase2_stage1_epoch_rows(araim_rows: list[dict[str, str]]) -> list[dict[str, Any]]:
    rows = []
    for row in araim_rows:
        if (row.get("row_type") or "").strip() != "epoch":
            continue
        stamp = to_float(row.get("stamp"))
        if stamp is None:
            continue
        item: dict[str, Any] = dict(row)
        item["stamp"] = stamp
        item["HPL"] = phase2_first_numeric(row, ["HPL"])
        item["VPL"] = phase2_first_numeric(row, ["VPL"])
        item["HAL"] = phase2_first_numeric(row, ["HAL"])
        item["VAL"] = phase2_first_numeric(row, ["VAL"])
        item["IM_H"] = item["HAL"] - item["HPL"] if item["HAL"] is not None and item["HPL"] is not None else math.nan
        item["IM_V"] = item["VAL"] - item["VPL"] if item["VAL"] is not None and item["VPL"] is not None else math.nan
        item["IM_min"] = (
            min(value for value in [item["IM_H"], item["IM_V"]] if math.isfinite(value))
            if any(math.isfinite(value) for value in [item["IM_H"], item["IM_V"]])
            else math.nan
        )
        item["n_vis"] = phase2_first_numeric(row, ["n_vis", "n_sv"])
        item["pdop"] = phase2_first_numeric(row, ["pdop", "PDOP"])
        item["lidar_alpha"] = phase2_first_numeric(
            row,
            ["lidar_alpha", "alpha_after_current_modulation", "alpha_after", "alpha_before_current_modulation", "alpha"],
        )
        item["tdop"] = phase2_first_numeric(row, ["tdop", "TDOP", "lidar_tdop"])
        item["query_source"] = first_value(row, ["query_source", "final_PL_source", "final_HPL_source", "source"]) or "UNKNOWN"
        item["fallback_reason"] = first_value(row, ["fallback_reason", "fallback", "reason"]) or "UNKNOWN"
        item["risk_band"] = phase2_first_numeric(row, ["risk_band"])
        item["scenario"] = first_value(row, ["scenario", "scenario_name", "scenario_id", "gnss_scenario_file"]) or "UNKNOWN"
        item["gnss_hpl"] = phase2_first_numeric(row, ["gnss_HPL", "HPL"])
        item["fused_hpl"] = phase2_first_numeric(row, ["HPL"])
        item["fused_minus_gnss_hpl"] = (
            item["fused_hpl"] - item["gnss_hpl"]
            if item["fused_hpl"] is not None and item["gnss_hpl"] is not None
            else math.nan
        )
        item["lidar_tdop"] = phase2_first_numeric(row, ["lidar_tdop", "tdop", "TDOP"])
        item["lidar_condition"] = phase2_first_numeric(row, ["lidar_condition", "condition", "condition_number"])
        rows.append(item)
    rows.sort(key=lambda item: float(item["stamp"]))
    return rows


