        pred_vpl = phase2_usable_plot_value(pred.get("PL_V_pred"))
        truth_hpl = phase2_usable_plot_value(truth.get(f"truth_{source}_HPL"))
        truth_vpl = phase2_usable_plot_value(truth.get(f"truth_{source}_VPL"))
