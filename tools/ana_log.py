    lines.append(md_table(
        ["Key", "Value"],
        [
            ["run_dir", run_dir],
            ["process_name", run_info.get("process_name", "")],
            ["start_timestamp", run_info.get("start_timestamp", "")],
            ["git_commit", run_info.get("git_commit", "")],
            ["build_type", run_info.get("build_type", "")],
            ["config_dir", run_info.get("config_dir", "")],
            ["source_root", run_info.get("source_root", "")],
        ],
    ))
