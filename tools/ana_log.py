def generate_phase2_truth_pi_hvpl_comparison_svg(
    phase2_analysis: dict[str, Any],
    truth_analysis: dict[str, Any],
    source: str,
    path: Path,
) -> None:
    label = "GNSS" if source == "gnss" else "LiDAR"
    width, height = 1120, 820
    body: list[str] = [
        svg_text(40, 34, f"Phase 2 PI Prediction vs Truth-Pose {label} ARAIM HPL/VPL", 18, "#111827")
    ]
    tolerance_s = float(to_float(phase2_analysis.get("match_tolerance_s")) or 0.10)
    rows = phase2_truth_pi_aligned_rows(phase2_analysis, truth_analysis, source, tolerance_s)
    if not phase2_analysis.get("available"):
        body.append(svg_text(40, 80, "Phase 2 prediction analysis is unavailable.", 14, "#991b1b"))
        write_svg(path, width, height, body)
        return
    if not truth_analysis.get("available"):
        body.append(svg_text(40, 80, "Truth-pose ARAIM baseline CSV is unavailable.", 14, "#991b1b"))
        body.append(svg_text(40, 106, "Run demo10 again so export/demo10_araim_truth_compare.csv is produced.", 12, "#4b5563"))
        write_svg(path, width, height, body)
        return
    if not rows:
        body.append(svg_text(40, 80, f"No paired {label} truth baseline and PI prediction rows within {tolerance_s:.3f}s.", 14, "#991b1b"))
        body.append(svg_text(40, 106, "PI prediction uses Phase2 PL_H_pred/PL_V_pred; truth baseline uses truth-pose ARAIM HPL/VPL.", 12, "#4b5563"))
        write_svg(path, width, height, body)
        return

    t0, t1 = phase2_time_bounds(rows, "sample_abs_time")
    rel_label = f"relative time from {t0:.3f}s"

    def valid_pairs(pred_key: str, truth_key: str) -> list[dict[str, Any]]:
        return [
            row
            for row in rows
            if to_float(row.get(pred_key)) is not None and to_float(row.get(truth_key)) is not None
        ]

    def add_timeline(
        px: float,
        py: float,
        pw: float,
        ph: float,
        title: str,
        pred_key: str,
        truth_key: str,
        delta_key: str,
    ) -> None:
        panel_rows = valid_pairs(pred_key, truth_key)
        body.extend(svg_axes(px, py, pw, ph, title, rel_label, "meters"))
        if not panel_rows:
            body.append(svg_text(px + 20, py + 42, "No paired finite values.", 13, "#991b1b"))
            return
        values = phase2_series_values(panel_rows, [pred_key, truth_key], True)
        y0, y1 = float_range(values)
        y0 = min(0.0, y0)
        body.append(svg_polyline(phase2_time_points(panel_rows, "sample_abs_time", truth_key, px, py, pw, ph, t0, t1, y0, y1, True), "#0891b2", 2.1, 0.95))
        body.append(svg_polyline(phase2_time_points(panel_rows, "sample_abs_time", pred_key, px, py, pw, ph, t0, t1, y0, y1, True), "#7c3aed", 1.9, 0.92))
        deltas = [to_float(row.get(delta_key)) for row in panel_rows if to_float(row.get(delta_key)) is not None]
        mean_delta = sum(deltas) / len(deltas) if deltas else math.nan
        under_count = sum(1 for row in panel_rows if float(row[pred_key]) < float(row[truth_key]))
        body.append(svg_text(px + 12, py + ph - 34, f"paired={len(panel_rows)}, PI<truth={under_count}, mean(PI-truth)={phase2_display_number(mean_delta)}m", 12, "#111827"))
        body.append(svg_text(px + 12, py + ph - 14, f"mean match dt={phase2_display_number(phase2_mean([row.get('match_dt_s') for row in panel_rows]))}s", 12, "#4b5563"))
        for idx, (name, color) in enumerate([(f"truth-pose {label}", "#0891b2"), ("PI predicted", "#7c3aed")]):
            body.append(f'<line x1="{px + pw - 220:.2f}" y1="{py + 22 + idx * 20:.2f}" x2="{px + pw - 190:.2f}" y2="{py + 22 + idx * 20:.2f}" stroke="{color}" stroke-width="2.2" />')
            body.append(svg_text(px + pw - 182, py + 26 + idx * 20, name, 11, "#374151"))
        body.append(svg_text(px - 8, py + ph + 4, f"{y0:.2f}", 10, "#4b5563", "end"))
        body.append(svg_text(px - 8, py + 4, f"{y1:.2f}", 10, "#4b5563", "end"))

    def add_scatter(
        px: float,
        py: float,
        pw: float,
        ph: float,
        title: str,
        pred_key: str,
        truth_key: str,
    ) -> None:
        paired = valid_pairs(pred_key, truth_key)
        body.extend(svg_axes(px, py, pw, ph, title, "truth-pose baseline [m]", "PI predicted [m]"))
        if not paired:
            body.append(svg_text(px + 20, py + 42, "No paired finite values.", 13, "#991b1b"))
            return
        values = []
        for row in paired:
            values.extend([float(row[truth_key]), float(row[pred_key])])
        lo, hi = float_range(values)
        lo = min(0.0, lo)
        p0 = (map_linear(lo, lo, hi, px, px + pw), map_linear(lo, lo, hi, py + ph, py))
        p1 = (map_linear(hi, lo, hi, px, px + pw), map_linear(hi, lo, hi, py + ph, py))
        body.append(f'<line x1="{p0[0]:.2f}" y1="{p0[1]:.2f}" x2="{p1[0]:.2f}" y2="{p1[1]:.2f}" stroke="#6b7280" stroke-dasharray="5 4" />')
        stride = max(1, len(paired) // 800)
        for row in paired[::stride]:
            truth = float(row[truth_key])
            pred = float(row[pred_key])
            color = "#16a34a" if pred >= truth else "#dc2626"
            x = map_linear(truth, lo, hi, px, px + pw)
            y = map_linear(pred, lo, hi, py + ph, py)
            body.append(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="3.0" fill="{color}" fill-opacity="0.72" />')
        body.append(svg_text(px + 12, py + ph - 12, f"green: PI>=truth, red: PI<truth, paired={len(paired)}", 12, "#111827"))
        body.append(svg_text(px - 8, py + ph + 4, f"{lo:.2f}", 10, "#4b5563", "end"))
        body.append(svg_text(px - 8, py + 4, f"{hi:.2f}", 10, "#4b5563", "end"))

    add_timeline(70.0, 80.0, 990.0, 210.0, f"{label} HPL timeline", "pred_HPL", "truth_HPL", "delta_HPL")
    add_timeline(70.0, 360.0, 990.0, 210.0, f"{label} VPL timeline", "pred_VPL", "truth_VPL", "delta_VPL")
    add_scatter(70.0, 660.0, 450.0, 120.0, f"{label} HPL scatter", "pred_HPL", "truth_HPL")
    add_scatter(610.0, 660.0, 450.0, 120.0, f"{label} VPL scatter", "pred_VPL", "truth_VPL")
    body.append(svg_text(70, 810, "Note: current PI-lite PL_H_pred/PL_V_pred are source-agnostic predictions from /iap/integrity, compared against source-specific truth-pose baselines.", 12, "#4b5563"))
    write_svg(path, width, height, body)


