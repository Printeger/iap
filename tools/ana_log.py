def format_triplet(item: dict[str, Any], min_instead: bool = False) -> str:
    last_key = "min" if min_instead else "max"
    return f"{item.get('mean', 0.0):.3f} / {item.get('p95', 0.0):.3f} / {item.get(last_key, 0.0):.3f}"


def build_json_payload(
    run_dir: Path,
    metadata: dict[str, Any],
    artifacts: list[ArtifactStatus],
    runtime: dict[str, Any],
    analyses: dict[str, Any],
    generated_plots: list[str],
    external_results: list[dict[str, Any]],
) -> dict[str, Any]:
    return {
        "run_dir": str(run_dir),
        "metadata": metadata,
        "artifact_statuses": [artifact.__dict__ for artifact in artifacts],
        "runtime_summary": {
            "total_lines": runtime.get("total_lines", 0),
            "level_counts": dict(runtime.get("level_counts", {})),
            "logger_counts": dict(runtime.get("logger_counts", {})),
            "loaded_modules": runtime.get("loaded_modules", []),
            "shutdown_messages": runtime.get("shutdown_messages", []),
            "save_messages": runtime.get("save_messages", []),
            "issues": runtime.get("issues", []),
            "top_patterns": runtime.get("top_patterns", []),
        },
        "analyses": analyses,
        "generated_plots": generated_plots,
        "external_results": external_results,
    }


def main() -> int:
    args = parse_args()
    run_dir = resolve_run_dir(args.run)
    out_dir = Path(args.out).resolve() if args.out else run_dir / "analysis"
    figs_dir = out_dir / "figs"
    ensure_dir(out_dir)
    ensure_dir(figs_dir)

    metadata = load_metadata(run_dir)
    runtime = parse_runtime_logs(run_dir)
    artifacts = scan_artifacts(run_dir, metadata)
    paths = artifact_paths(run_dir)
    rows_by_name = {
        name: load_csv_rows(path)
        for name, (path, _rel, _aliases) in paths.items()
        if path is not None and path.suffix == ".csv"
    }

    analyses = {
        "timing": analyze_timing(rows_by_name.get("timing", [])),
        "icp": analyze_icp(rows_by_name.get("icp", [])),
        "gnss_factor_debug": analyze_gnss(rows_by_name.get("gnss_factor_debug", [])),
        "araim": analyze_araim(rows_by_name.get("araim", [])),
        "demo8_araim_truth_compare": analyze_demo8_araim_truth_compare(
            rows_by_name.get("demo8_araim_truth_compare", [])
        ),
        "sim_truth_integrity": analyze_sim_truth_integrity(
            rows_by_name.get("truth_vs_est", []),
            rows_by_name.get("araim", []),
            metadata,
        ),
        "desired_tracking": analyze_desired_tracking(rows_by_name.get("desired_vs_truth", [])),
        "trajectory": analyze_trajectory(rows_by_name.get("trajectory", [])),
        "dump": analyze_dump(run_dir),
    }

    generated_plots = maybe_generate_timing_plot(analyses["timing"], figs_dir, args.no_plots)
    generated_plots.extend(
        write_demo8_araim_truth_compare_outputs(
            analyses["demo8_araim_truth_compare"],
            out_dir,
            figs_dir,
            args.no_plots,
            rows_by_name.get("gnss_factor_debug", []),
            rows_by_name.get("araim", []),
        )
    )
    generated_plots.extend(
        write_sim_integrity_outputs(analyses["sim_truth_integrity"], out_dir, figs_dir, args.no_plots)
    )
    external_results: list[dict[str, Any]] = []
    if not args.skip_external_tools:
        external_results = integrate_external_plots(run_dir, rows_by_name, figs_dir / "external")

    report_md = render_report(run_dir, metadata, artifacts, runtime, analyses, generated_plots, external_results)
    report_md_path = out_dir / "report.md"
    report_json_path = out_dir / "report.json"
    report_md_path.write_text(report_md, encoding="utf-8")
    report_json_path.write_text(
        json.dumps(
            build_json_payload(run_dir, metadata, artifacts, runtime, analyses, generated_plots, external_results),
            indent=2,
            ensure_ascii=False,
        )
        + "\n",
        encoding="utf-8",
    )

    print(f"Analyzed run: {run_dir}")
    print(f"Markdown report: {report_md_path}")
    print(f"JSON report    : {report_json_path}")
    print(f"Figures dir     : {figs_dir}")

    if args.strict:
        has_runtime_error = any(issue["level"] in {"error", "critical"} for issue in runtime.get("issues", []))
        missing_enabled = any(artifact.status == "expected_missing" for artifact in artifacts)
        if has_runtime_error or missing_enabled:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
