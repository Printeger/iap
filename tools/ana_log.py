def generate_exec_trajectory_svg(analysis: dict[str, Any], path: Path) -> None:
    rows = analysis["rows"]
    W, H = 900, 720
    PAD_L, PAD_R, PAD_T, PAD_B = 75, 30, 50, 45
    pw = W - PAD_L - PAD_R
    ph = (H - PAD_T - PAD_B - 90) // 4

    ts = [to_float(r.get("t_s")) for r in rows]
    xs = [to_float(r.get("x_m")) for r in rows]
    ys = [to_float(r.get("y_m")) for r in rows]
    zs = [to_float(r.get("z_m")) for r in rows]
    vxs = [to_float(r.get("vx")) for r in rows]
    vys = [to_float(r.get("vy")) for r in rows]
    vzs = [to_float(r.get("vz")) for r in rows]
    modes = [r.get("mode", "") for r in rows]

    ts_ok = [v for v in ts if v is not None]
    t0 = min(ts_ok) if ts_ok else 0.0
    t1 = max(ts_ok) if ts_ok else 1.0
    if math.isclose(t0, t1):
        t1 = t0 + 1.0

    valid_pos = [
        (ts[i], xs[i], ys[i], zs[i])
        for i in range(len(rows))
        if ts[i] is not None and xs[i] is not None and ys[i] is not None and zs[i] is not None
    ]
    valid_spd = [
        (ts[i], math.sqrt(vxs[i] ** 2 + vys[i] ** 2 + vzs[i] ** 2))
        for i in range(len(rows))
        if ts[i] is not None and vxs[i] is not None and vys[i] is not None and vzs[i] is not None
    ]

    body: list[str] = []

    # Panel 1: altitude (z) over time
    y0 = PAD_T
    z_vals = [v[3] for v in valid_pos]
    z_lo = min(z_vals) if z_vals else 0.0
    z_hi = max(z_vals) if z_vals else 1.0
    if math.isclose(z_lo, z_hi):
        z_hi = z_lo + 1.0
    body += svg_axes(PAD_L, y0, pw, ph, "Altitude (z_m) over Time", "Time (s)", "z (m)")
    z_pts = [
        (map_linear(v[0], t0, t1, PAD_L, PAD_L + pw), map_linear(v[3], z_lo, z_hi, y0 + ph, y0))
        for v in valid_pos
    ]
    body.append(svg_polyline(z_pts, "#1f77b4"))

    # Panel 2: speed over time
    y1 = y0 + ph + 30
    spd_vals = [v[1] for v in valid_spd]
    spd_hi = max(spd_vals) if spd_vals else 1.0
    if math.isclose(spd_hi, 0.0):
        spd_hi = 1.0
    body += svg_axes(PAD_L, y1, pw, ph, "Speed over Time", "Time (s)", "speed (m/s)")
    spd_pts = [
        (map_linear(v[0], t0, t1, PAD_L, PAD_L + pw), map_linear(v[1], 0.0, spd_hi * 1.1, y1 + ph, y1))
        for v in valid_spd
    ]
    body.append(svg_polyline(spd_pts, "#2ca02c"))

    # Panel 3: flight mode lane
    y2 = y1 + ph + 30
    mode_colors = {
        "MISSION": "#2ca02c", "HOLD": "#ff7f0e", "RTL": "#d62728",
        "LAND": "#9467bd", "MANUAL": "#8c564b",
    }
    body += svg_axes(PAD_L, y2, pw, 30, "Flight Mode", "Time (s)", "")
    for i, t_val in enumerate(ts):
        if t_val is None:
            continue
        cx = map_linear(t_val, t0, t1, PAD_L, PAD_L + pw)
        color = mode_colors.get(modes[i], "#6b7280")
        body.append(f'<circle cx="{cx:.2f}" cy="{y2 + 15:.2f}" r="4" fill="{color}" />')
    lx = PAD_L
    for label, color in mode_colors.items():
        body.append(f'<circle cx="{lx + 6:.2f}" cy="{y2 + 44:.2f}" r="5" fill="{color}" />')
        body.append(svg_text(lx + 15, y2 + 48, label, 9, "#4b5563", "start"))
        lx += 80

    # Panel 4: 2-D ground track (x vs y)
    y3 = y2 + 30 + 30
    x_vals = [v[1] for v in valid_pos]
    y_vals = [v[2] for v in valid_pos]
    x_lo = min(x_vals) if x_vals else 0.0
    x_hi = max(x_vals) if x_vals else 1.0
    y_lo = min(y_vals) if y_vals else 0.0
    y_hi = max(y_vals) if y_vals else 1.0
    if math.isclose(x_lo, x_hi):
        x_hi = x_lo + 1.0
    if math.isclose(y_lo, y_hi):
        y_hi = y_lo + 1.0
    body += svg_axes(PAD_L, y3, pw, ph, "Ground Track (x vs y)", "x (m)", "y (m)")
    gt_pts = [
        (map_linear(v[1], x_lo, x_hi, PAD_L, PAD_L + pw), map_linear(v[2], y_lo, y_hi, y3 + ph, y3))
        for v in valid_pos
    ]
    body.append(svg_polyline(gt_pts, "#9467bd", 1.0))
    if gt_pts:
        body.append(f'<circle cx="{gt_pts[0][0]:.2f}" cy="{gt_pts[0][1]:.2f}" r="5" fill="#2ca02c" />')
        body.append(f'<circle cx="{gt_pts[-1][0]:.2f}" cy="{gt_pts[-1][1]:.2f}" r="5" fill="#d62728" />')

    write_svg(path, W, H, body)


