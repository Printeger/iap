    if issues:
        lines.append("")
        lines.append(md_table(
            ["File", "Line", "Level", "Message"],
            [[item["file"], item["line"], item["level"], item["message"][:240]] for item in issues[:30]],
        ))
    if runtime.get("top_patterns"):
        lines.append("")
        lines.append(md_table(
            ["Count", "Pattern"],
            [[count, pattern] for pattern, count in runtime["top_patterns"]],
        ))
    lines.append("")

