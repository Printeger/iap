    lines.append("")

    lines.append("## External Plot Integrations")
    lines.append("")
    if external_results:
        lines.append(md_table(
            ["Script", "Return Code", "Stdout", "Stderr"],
            [[item["script"], item["returncode"], item["stdout"][:160], item["stderr"][:240]] for item in external_results],
        ))
    else:
        lines.append("No external analysis scripts were invoked.")
    lines.append("")
    return "\n".join(lines)


