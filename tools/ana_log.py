def phase2_mean(values: list[Any]) -> float | None:
    usable = [phase2_as_float(value) for value in values if phase2_finite(value)]
    return sum(usable) / len(usable) if usable else None


def phase2_quantile(values: list[Any], q: float) -> float | None:
    usable = sorted(phase2_as_float(value) for value in values if phase2_finite(value))
    if not usable:
        return None
    if len(usable) == 1:
        return usable[0]
    pos = (len(usable) - 1) * q
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    if lo == hi:
        return usable[lo]
    return usable[lo] * (hi - pos) + usable[hi] * (pos - lo)


def phase2_build_index(rows: list[dict[str, str]], time_key: str) -> tuple[list[float], list[dict[str, str]]]:
    indexed = []
    for row in rows:
        stamp = to_float(row.get(time_key))
        if stamp is not None:
            indexed.append((stamp, row))
    indexed.sort(key=lambda item: item[0])
    return [item[0] for item in indexed], [item[1] for item in indexed]


def phase2_nearest(
    indexed: tuple[list[float], list[dict[str, str]]],
    target: Any,
    tolerance_s: float,
) -> tuple[dict[str, str] | None, float]:
    times, rows = indexed
    target_stamp = to_float(target)
    if target_stamp is None or not times:
        return None, math.nan
    pos = bisect.bisect_left(times, target_stamp)
    candidates: list[tuple[float, dict[str, str]]] = []
    if pos < len(times):
        candidates.append((times[pos], rows[pos]))
    if pos > 0:
        candidates.append((times[pos - 1], rows[pos - 1]))
    if not candidates:
        return None, math.nan
    best_stamp, best_row = min(candidates, key=lambda item: abs(item[0] - target_stamp))
    dt = abs(best_stamp - target_stamp)
    if dt <= tolerance_s:
        return best_row, dt
    return None, math.nan


def phase2_norm3(*values: Any) -> float:
    nums = [phase2_as_float(value) for value in values]
    if len(nums) != 6 or not all(math.isfinite(value) for value in nums):
        return math.nan
    return math.sqrt(
        (nums[0] - nums[3]) ** 2
        + (nums[1] - nums[4]) ** 2
        + (nums[2] - nums[5]) ** 2
    )


def phase2_label_from_im(value: Any) -> str:
    number = to_float(value)
    if number is None:
        return ""
    return "SAFE" if number >= 0.0 else "UNSAFE"


def phase2_safe_label_agreement(pred_im: Any, actual_im: Any) -> str:
    pred = phase2_label_from_im(pred_im)
    actual = phase2_label_from_im(actual_im)
    if not pred or not actual:
        return ""
    return "true" if pred == actual else "false"


def phase2_araim_values(row: dict[str, str] | None) -> tuple[float, float, float, float, float]:
    if row is None:
        return (math.nan,) * 5
    hpl = phase2_as_float(row.get("HPL"))
    vpl = phase2_as_float(row.get("VPL"))
    hal = phase2_as_float(row.get("HAL"))
    val = phase2_as_float(row.get("VAL"))
    actual_pl = max(hpl, vpl) if math.isfinite(hpl) and math.isfinite(vpl) else math.nan
    actual_al = min(hal, val) if math.isfinite(hal) and math.isfinite(val) else math.nan
    actual_im = phase2_as_float(row.get("IM"))
    if not math.isfinite(actual_im) and math.isfinite(actual_al) and math.isfinite(actual_pl):
        actual_im = actual_al - actual_pl
    return hpl, vpl, actual_pl, actual_al, actual_im


def phase2_estimate_desired_offset(
    pred_rows: list[dict[str, str]],
    desired_index: tuple[list[float], list[dict[str, str]]],
    tolerance_s: float,
) -> float:
    desired_times, _desired_rows = desired_index
    if not pred_rows or not desired_times:
        return 0.0
    sample = pred_rows[: min(100, len(pred_rows))]
    direct_matches = 0
    pred_times = []
    for row in sample:
        stamp = to_float(row.get("stamp"))
        t_from_now = to_float(row.get("sample_t_from_now"))
        if stamp is None or t_from_now is None:
            continue
        planner_time = stamp + t_from_now
        pred_times.append(planner_time)
        match, _dt = phase2_nearest(desired_index, planner_time, tolerance_s)
        if match is not None:
            direct_matches += 1
    if not pred_times or direct_matches / max(1, len(pred_times)) >= 0.10:
        return 0.0
    paired_desired = desired_times[: min(len(desired_times), len(pred_times))]
    if not paired_desired:
        return 0.0
    return median(paired_desired) - median(pred_times)


